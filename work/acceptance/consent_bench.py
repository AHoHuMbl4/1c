#!/usr/bin/env python3
"""ПРИБОР: «право на ответ» по СОГЛАСИЮ ПОВЕРХНОСТЕЙ (задача 15 реестра).

Мерило владельца 03.08 — считать ОШИБКИ, а не «правильность»: отвечать разрешено только
тогда, когда выбор ДОКАЗАН, а во всех остальных случаях законный выход — вопрос человеку.
Здесь меряется ровно одно правило: **отвечаем, только если независимые поверхности отбора
сошлись на одной сущности**.

Что считается поверхностью — то же, что в бою (`serene_ask.answer`), три независимых
источника кандидатов:
  1. `буквально` — слова строки через инвертированный индекс (`tables_of`);
  2. `синонимы`  — словарь сущности, собранный при установке (`alias_hits`);
  3. `смысл`     — kNN по карточке/метке сущности (`near_tables`).

Считаются ДВА вида согласия, потому что выбрать между ними должно число, а не вкус:
  * `вершины`  — поверхность голосует ТОЛЬКО за свою первую сущность;
  * `вхождение` — поверхность голосует за все сущности, которые она принесла.
Согласие есть, если ровно одна семья набрала голоса **двух и более** поверхностей.

🔴 ЧЕСТНЫЕ ГРАНИЦЫ ПРИБОРА — их три, и без них числа читать нельзя.

1. Понятия вопроса в бою формулирует модель (`parse_intent`); здесь берутся слова самого
   вопроса. Это то же приближение, что у `candidate_surfaces_bench`, и по той же причине:
   прибор обязан быть бесплатным и воспроизводимым. Приближение одинаково для всех трёх
   поверхностей, поэтому сравнение между ними честное.
2. Прибор НЕ знает, какую сущность выбрала бы модель: выбор сущности стоит денег. Поэтому
   он меряет не «продукт с правилом», а САМО ПРАВИЛО: если согласие есть — считаем, что
   ответ пошёл бы по согласованной семье. Это верхняя оценка пользы правила и нижняя
   оценка числа вопросов: в бою модель может выбрать сущность, которую правило затем
   отвергнет, и вопросов станет больше.
3. Табличная часть засчитывается за свой документ (`search_tables.parent`) — как и в
   остальных приборах: шапка против строк — отдельная задача (18), не эта.

Использование:
    SERENEDB_DSN_RO=… PGPASSWORD=… <переменные эмбеддера> \
        python3 work/acceptance/consent_bench.py [файл_набора]
"""
import importlib
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SET_FILE = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "docs/ACCEPTANCE_UT.md")

sys.path.insert(0, os.path.join(ROOT, "ubuntu/serenedb"))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.argv = [sys.argv[0], SET_FILE]

A = importlib.import_module("serene_ask")
B = importlib.import_module("entity_choice_bench")
# Поверхности берутся ИЗ СОСЕДНЕГО ПРИБОРА, а не переписываются здесь: правило «одно
# место правды» касается и приборов. Разойдись они — числа двух приборов стало бы
# невозможно сравнивать между собой.
S = importlib.import_module("candidate_surfaces_bench")

NAMES = ["буквально", "синонимы", "смысл"]


def votes(surf, par, by_top):
    """Голоса поверхностей: {семья: сколько поверхностей за неё}.

    `by_top=True` — поверхность голосует только за свою первую сущность; иначе за все.
    """
    out = {}
    for n in NAMES:
        lst = surf.get(n) or []
        if not lst:
            continue                    # молчащая поверхность не голосует и не спорит
        fams = [S.family(lst[0], par)] if by_top else \
            list(dict.fromkeys(S.family(t, par) for t in lst))
        for f in fams:
            out[f] = out.get(f, 0) + 1
    return out


def verdict(v):
    """Согласие — ровно одна семья с двумя и более голосами. Иначе спрашиваем.

    Порога тут нет: «две поверхности из трёх» — не подобранное число, а сам смысл слова
    «независимое подтверждение». Одна поверхность подтверждает сама себя.
    """
    best = [f for f, n in v.items() if n >= 2]
    if len(best) == 1:
        return best[0]
    return None


def main():
    par = {}
    for r in A.psql("SELECT src_table, coalesce(nullif(parent,''), src_table) FROM %s"
                    % A.TABLES):
        if r and r[0]:
            par[r[0]] = r[1]
    pairs = B.pairs(SET_FILE)
    tally = {k: {"верно": 0, "ошибка": 0, "спросили": 0} for k in ("вершины", "вхождение")}
    spoke = {n: 0 for n in NAMES}
    total = 0
    rows = []
    for q, want in pairs:
        surf = S.surfaces(q)
        if surf is None:
            continue
        total += 1
        wf = S.family(want, par)
        for n in NAMES:
            if surf.get(n):
                spoke[n] += 1
        line = [q[:46]]
        for mode, by_top in (("вершины", True), ("вхождение", False)):
            got = verdict(votes(surf, par, by_top))
            if got is None:
                tally[mode]["спросили"] += 1
                line.append("спросили")
            elif got == wf:
                tally[mode]["верно"] += 1
                line.append("верно")
            else:
                tally[mode]["ошибка"] += 1
                line.append("ОШИБКА")
        rows.append(line)

    # ВТОРАЯ ФОРМА ТОГО ЖЕ ПРАВИЛА — ВЕТО, а не выбор. В бою сущность называет модель, а
    # правило только решает, есть ли право ответить. Значит меряется другое: пропустило бы
    # вето ЭТАЛОН (сохранился бы верный ответ) и пропустило бы оно ЧУЖУЮ семью (осталась бы
    # ошибка). Правило, которое рубит верное и пропускает чужое, бесполезно в обе стороны.
    veto = {"эталон прошёл": 0, "чужая прошла": 0, "чужая прошла, эталон нет": 0}
    for q, want in pairs:
        surf = S.surfaces(q)
        if surf is None:
            continue
        wf = S.family(want, par)
        v = votes(surf, par, False)         # вхождение: самая мягкая форма вето
        ok_ref = v.get(wf, 0) >= 2
        others = [f for f, n in v.items() if n >= 2 and f != wf]
        veto["эталон прошёл"] += 1 if ok_ref else 0
        veto["чужая прошла"] += 1 if others else 0
        veto["чужая прошла, эталон нет"] += 1 if others and not ok_ref else 0

    print("%-46s %-10s %s" % ("вопрос", "вершины", "вхождение"))
    for line in rows:
        print("%-46s %-10s %s" % tuple(line))
    print("\nвопросов с эталонной сущностью: %d" % total)
    print("поверхность подала голос: " + ", ".join(
        "%s %d" % (n, spoke[n]) for n in NAMES))
    for mode in ("вершины", "вхождение"):
        t = tally[mode]
        print("\nсогласие по «%s»:" % mode)
        print("  🔴 ОШИБОК (согласились на чужой сущности): %d" % t["ошибка"])
        print("     верно (согласились на эталонной):       %d" % t["верно"])
        print("     не утверждал (спросили бы человека):    %d" % t["спросили"])
    print("\nвето (мягкая форма: семья подтверждена вхождением в ДВЕ поверхности):")
    print("  эталон прошёл вето — верный ответ уцелел бы: %d из %d" %
          (veto["эталон прошёл"], total))
    print("  чужая семья прошла вето — ошибка НЕ отсеяна: %d из %d" %
          (veto["чужая прошла"], total))
    print("  🔴 чужая прошла, а эталон нет — вето бьёт ровно наоборот: %d из %d" %
          (veto["чужая прошла, эталон нет"], total))
    return 0


if __name__ == "__main__":
    sys.exit(main())
