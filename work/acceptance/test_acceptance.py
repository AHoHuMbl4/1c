#!/usr/bin/env python3
"""Проба прибора приёмки подменой. Без базы, без сети, без модели.

`DEV_PLAN.md`, кластер Э1, «чем проверяется»: прибору подсовываются заведомо верный
ответ, заведомо неверный, отказ и уточнение — он обязан назвать все четыре правильно.
Здесь это сделано и расширено случаями, которые прежняя редакция засчитывала неверно.

Запуск: `python3 work/acceptance/test_acceptance.py` (код возврата 1 при любом провале).
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import run_acceptance as R  # noqa: E402

# Набор-образец: те же формы записи, что в docs/ACCEPTANCE_UT.md, включая заголовок с
# пояснением после кавычек (на нём прежний прибор терял четыре вопроса из 58).
DOC = """
**1. «Сколько заказов клиентов оформлено и на какую сумму?»**
- SQL: `select 1;`
- эталон: **186 заказов, 14 631 167,72**
- провал: 234 заказа (строки).

**2. «Какой самый ранний документ в базе?»**
- эталон: **0016-12-22 12:00:00** — в 1С у документа проставлен год «16».
- ожидаемый `kind`: `answer`, называющий аномалию, либо `clarify`
- провал: 2014 (первый «нормальный» год)

**3. «На какую сумму продали ООО Ромашка?»**
- ожидаемый `kind`: `no_data`
- провал: `answer` с любым числом

**4. «На какую сумму?»** (вопрос без предмета)
- ожидаемый `kind`: `clarify`
- провал: `answer` с любым числом; `unavailable`.

**5. «У кого из сотрудников самая ранняя дата рождения?»**
- эталон: **Тюренкова Наталья Сергеевна**
- ожидаемый `kind`: `answer`
"""

CASES = {c['no']: c for c in R.parse_cases(DOC)}
FAILED = []


def obs(human, service, called=True, error=None):
    return {'human': human, 'service': service, 'called': called, 'error': error}


def probe(name, no, o, want):
    code, why = R.verdict(CASES[no], o)
    ok = code == want
    print('%-4s %-58s → %-9s %s' % ('OK' if ok else '🔴', name, code,
                                    '' if ok else '(ждали %s: %s)' % (want, why)))
    if not ok:
        FAILED.append(name)


print('== разбор набора ==')
if len(CASES) != 5:
    FAILED.append('прочитано %d вопросов из 5' % len(CASES))
    print('🔴 прочитано вопросов: %d из 5' % len(CASES))
else:
    print('OK   все 5 вопросов прочитаны, включая заголовок с пояснением после кавычек')

# Составной эталон разбирается в перечень величин, а не в одно число.
if CASES[1]['ref']['nums'] != [186.0, 14631167.72]:
    FAILED.append('составной эталон разобран как %s' % CASES[1]['ref']['nums'])
    print('🔴 составной эталон: %s' % CASES[1]['ref']['nums'])
else:
    print('OK   составной эталон «186 заказов, 14 631 167,72» → [186.0, 14631167.72]')

# Перечень провалов читается и без жирного выделения.
if 234.0 not in CASES[1]['fails'] or 2014.0 not in CASES[2]['fails']:
    FAILED.append('перечень провалов прочитан неполно')
    print('🔴 провалы: %s / %s' % (CASES[1]['fails'], CASES[2]['fails']))
else:
    print('OK   перечень провалов читается без жирного выделения')

print('\n== четыре подмены, которых требует DEV_PLAN ==')
probe('заведомо верный ответ', 1,
      obs('Оформлено 186 заказов на 14 631 167,72 руб.', 'Оформлено 186 заказов на 14 631 167,72 руб.'),
      'ok')
probe('заведомо неверный ответ', 1,
      obs('Оформлено 234 заказа на 14 631 167,72 руб.', 'Оформлено 234 заказа.'),
      'fail')
probe('отказ там, где его ждут', 3,
      obs('Такого контрагента в данных нет.', '[NO DATA] Tell the user there is no such data.'),
      'ok')
probe('уточнение там, где его ждут', 4,
      obs('Уточните, о какой сумме речь?', '[CLARIFICATION NEEDED] Put the question below...'),
      'clarify')

print('\n== то, что прежняя редакция засчитывала неверно ==')
# F210: ветка поведения вырождалась в «есть любое число → ВЕРНО».
probe('F210: любое число вместо эталона', 1,
      obs('Заказов примерно 42.', 'Заказов 42.'), 'wrong')
# Самый опасный класс: сервис данных не дал, модель назвала число.
probe('сервис сказал no_data, модель назвала число', 3,
      obs('Продано на 186 руб.', '[NO DATA] Tell the user there is no such data.'), 'wrong')
# F211: союз «или» в ответе больше не превращает ответ в «уточнение».
probe('F211: «или» в верном ответе не делает его уточнением', 1,
      obs('186 заказов, или 14 631 167,72 руб. в деньгах.',
          '186 заказов, или 14 631 167,72 руб. в деньгах.'), 'ok')
# F212: язык ответа роли не играет — kind берётся из маркера моста.
probe('F212: тот же отказ по-английски', 3,
      obs('There is no such counterparty in the data.',
          '[NO DATA] Tell the user there is no such data.'), 'ok')
probe('F212: то же уточнение по-английски', 4,
      obs('Which amount do you mean?', '[CLARIFICATION NEEDED] Put the question below...'),
      'clarify')
# Эталон без чисел и дат — прибор обязан сказать, что не проверил, а не «ВЕРНО».
# 🔴 Это вторая ветка F210, найденная этой же пробой: «ждали answer, получили answer»
# засчитывалось за верный ответ, хотя проверено не было ничего.
probe('эталон именем: прибор не проверяет, но и не хвалит', 5,
      obs('Самая ранняя дата рождения у Тюренковой Натальи Сергеевны.',
          'Тюренкова Наталья Сергеевна, 1669-05-14'), 'unchecked')
probe('«ждали answer, получили answer» — не доказательство', 5,
      obs('Их примерно сорок.', 'Их примерно сорок.'), 'unchecked')
# Мост 02.08 начал ставить маркер [FIGURES] (кластер Э4, F129). Прибор обязан понимать
# оба состояния моста: неизвестный маркер он принял бы за начало обычного ответа.
probe('маркер [FIGURES] — это ответ по данным, а не сбой', 1,
      obs('Оформлено 186 заказов на 14 631 167,72 руб.',
          '[FIGURES] The values below ARE computed by the database.\n186; 14 631 167,72'),
      'ok')
probe('[FIGURES] с не тем числом — по-прежнему провал', 1,
      obs('Оформлено 234 заказа.', '[FIGURES] ...\n234'), 'fail')
# №24: внешний сбой — не неверный ответ.
probe('№24: внешний сбой не считается неверным ответом', 1,
      obs('', None, called=False, error='TimeoutExpired'), 'broken')
probe('ответ без обращения к данным — дефект, а не успех', 1,
      obs('Заказов 186 на 14 631 167,72.', None, called=False), 'wrong')

print('\n== разбор чисел и дат ==')


def eq(name, got, want):
    ok = got == want
    print('%-4s %-58s %s' % ('OK' if ok else '🔴', name, '' if ok else '%s ≠ %s' % (got, want)))
    if not ok:
        FAILED.append(name)


# F211: склейка цифр через пробел делала из двух чисел третье.
eq('«12 5» — два числа, а не 125', R.nums('12 5'), [12.0, 5.0])
eq('«1 200 000» — одно число', R.nums('1 200 000'), [1200000.0])
eq('«227 позиций и 92 683 штук»', R.nums('227 позиций и 92 683 штук'), [227.0, 92683.0])
eq('дата не распадается на числа', R.nums('2016-02-24 14:36:49'), [])
eq('дата ISO читается как дата', R.dates('самый ранний — 0016-12-22'), ['0016-12-22'])
# Дата, названная словами на языке ответа, засчитывается по году и дню.
eq('дата словами: год и день на месте',
   R.check_values({'nums': [], 'dates': ['2016-02-24']}, 'от 24 февраля 2016 года'), [])
eq('дата словами: другой день — не совпало',
   R.check_values({'nums': [], 'dates': ['2016-02-24']}, 'от 25 февраля 2016 года'),
   ['2016-02-24'])

print()
if FAILED:
    print('🔴 ПРОВАЛОВ: %d — %s' % (len(FAILED), '; '.join(FAILED)))
    sys.exit(1)
print('Прибор прошёл пробу подменой полностью.')
