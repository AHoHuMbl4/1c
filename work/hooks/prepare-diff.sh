#!/usr/bin/env bash
# Готовит дифф коммита для снайпера-агента: кладёт `git diff --cached` в файл.
#
# 🔴 ЗАЧЕМ. Снайпер на страже коммита — хук типа `agent`: он читает дифф и ищет смысловые
# вещи, которые регуляркой не выразить («этот цикл — велосипед поверх штатного `ts_compound`»).
# Дифф он добывал сам, вызывая оболочку, — и 03.08 упёрся: в режиме, где оболочка ему не
# разрешена, он честно отказался подтверждать чистоту и заблокировал ВСЕ коммиты.
#
# Отказ был правильный (молчаливое «OK» без проверки — ложь), неправильной была связка:
# проверка зависела от режима разрешений, а не от кода. Теперь дифф ему ПОДАЁТСЯ: этот хук
# идёт в цепочке раньше и складывает дифф в файл, который снайпер читает обычным чтением.
#
# Заменять умного снайпера набором регулярок было бы потерей: форму (числовые отсечки,
# кириллицу в литералах) уже ловит `check-diff.sh`, а смысл — только модель.
set -uo pipefail

. "$(dirname "${BASH_SOURCE[0]}")/lib-hooks.sh"
CMD=$(hook_command)
is_git_commit "$CMD" || { echo '{}'; exit 0; }

cd_repo || { hook_ask "Хук $(basename "$0") не смог определить каталог репозитория: снайперу нечего будет читать."; exit 0; }

OUT=".claude/state/staged.diff"
mkdir -p .claude/state 2>/dev/null

# Дифф пишется целиком, без усечения: снайпер обязан видеть то же, что уедет в историю.
# Не записалось — это не повод проверять «по памяти»: пусть снайпер увидит явную пометку
# и потребует разобраться, а не выдаст чистый вердикт по пустому файлу.
if git diff --cached > "$OUT" 2>/dev/null; then
  if [ -s "$OUT" ]; then
    hook_log "prepare-diff" "дифф подан снайперу ($(wc -c < "$OUT") байт)"
  else
    printf 'ДИФФ ПУСТ: в индексе ничего нет.\n' > "$OUT"
    hook_log "prepare-diff" "индекс пуст"
  fi
else
  printf 'ДИФФ НЕ СНЯТ: git diff --cached не отработал. Проверку считать невыполненной.\n' > "$OUT"
  hook_log "prepare-diff" "🔴 дифф не снят"
fi

echo '{}'
