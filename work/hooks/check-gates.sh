#!/usr/bin/env bash
# Сторож самой защиты: перед коммитом и перед выкатом проверяет, что гейты на месте.
#
# 🔴 ЗАЧЕМ ОТДЕЛЬНЫЙ ХУК. Все прочие гейты проверяют РАБОТУ (документы, граф, SQL, промты).
# Ни один не проверял САМИ ГЕЙТЫ, а разоружить их можно одной правкой: убрать хук из
# `settings.json`, вернуть вердикт `ask`, снять `core.hooksPath`, выпотрошить обёртку
# `.githooks/pre-commit`. Каждый из четырёх способов выглядит как обычная работа и не
# оставляет ни одного срабатывания — защита исчезает молча, и это худший вид отказа.
#
# Пара к нему — `.claude/hooks/git-gate.sh`: тот же список проверяется и на стороне git,
# то есть в сессии без хуков движка (Cursor, руки владельца, дочерняя сессия). Два
# сторожа с разных сторон: пропустить надо оба.
set -uo pipefail

. "$(dirname "${BASH_SOURCE[0]}")/lib-hooks.sh"
CMD=$(hook_command)

# 🔴 ПОДСКАЗКА ВМЕСТО ТУПИКА. Повышение прав сессии закрыто её собственной средой, и
# попытка перезапустить сервис через него упирается намертво: работа встаёт, а владельцу
# уходит просьба «наберите, пожалуйста». Между тем повышение и не нужно — юниты `1c-*`
# разрешены правилом polkit, пользовательский шлюз бота перезапускается юнитом-обёрткой.
# Правило, о котором исполнитель узнаёт из документа, работает хуже правила, которое
# говорит с ним в момент действия: 04.08 просьба пришла дважды уже после того, как
# прямой путь был сделан и записан в CLAUDE.md.
if printf '%s' "$CMD" | grep -qE '(^|[;&|]|[[:space:]])sudo([[:space:]]|$)' \
   && printf '%s' "$CMD" | grep -q 'systemctl'; then
  hook_stop "check-gates" "Повышение прав здесь не нужно — и оно всё равно закрыто средой.

Юниты проекта перезапускаются напрямую:
  systemctl restart 1c-serene-ask@ut_test 1c-serene-ask@postgres
Пользовательский шлюз бота (openclaw-gateway под undebot) — юнитом-обёрткой:
  systemctl start 1c-openclaw-gateway-restart

Разрешено ровно это: правило polkit 50-claudedev-1c-units.rules покрывает юниты 1c-*;
чужие (cron, polkit и прочие) по-прежнему требуют администратора."
  exit 0
fi

is_git_commit "$CMD" || is_deploy "$CMD" || { echo '{}'; exit 0; }

cd_repo || { hook_ask "Хук $(basename "$0") не смог определить каталог репозитория и ничего не проверил. Пропускать проверку молча нельзя."; exit 0; }

BROKEN="$(hook_guard_armed)"
if [ -z "$BROKEN" ]; then
  hook_log "check-gates" "тихо (защита цела)"
  echo '{}'
  exit 0
fi

hook_stop "check-gates" "Защита гейтов снята — работа продолжится, когда она вернётся:

$BROKEN
Правило проекта: запреты держатся кодом, а не текстом (CLAUDE.md). Гейт, который можно
выключить по дороге, — это текст с лишними шагами. Если защита снята намеренно и
ненадолго, пусть это будет отдельный коммит с объяснением, а не побочный след правки."
