#!/usr/bin/env bash
# Снайпер коммита для Kimi Code: смысловая проверка диффа моделью.
#
# 🔴 ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. В Claude Code снайпер — хук типа `agent` (см. settings.json):
# движок сам зовёт модель с промтом. У Kimi хуков типа agent нет — только вызов команды,
# поэтому модель зовёт этот скрипт процессом `kimi -p`. Проверяемое одно и то же: четыре
# находки, которые регуляркой не выразить (велосипед поверх штатного механизма SereneDB,
# подгонка отсечки под нашу базу, рост величины в модель без границы, имя нашей базы
# в исполняемом коде).
#
# 🔴 ДИФФ СНИМАЕТСЯ ЗДЕСЬ, А НЕ ЧИТАЕТСЯ ИЗ ФАЙЛА prepare-diff. Хуки Kimi на одно событие
# запускаются ПАРАЛЛЕЛЬНО (документация hooks), поэтому порядка «prepare-diff раньше
# снайпера» нет: чужой файл мог быть ещё не положен — или лежать от прошлой проверки.
# Проверка, читающая вчерашний дифф, хуже отсутствующей. Файл свой (staged-kimi.diff),
# чтобы параллельный prepare-diff не перезаписывал дифф посреди чтения.
# Тот же урок, что и у пустого индекса (коммит 0d75629): «не получил дифф» — это
# невыполненная проверка, а не «нечего проверять».
#
# Вердикт разбирается по строке-маяку (`VERDICT: OK` / `VERDICT: FINDINGS`), а не по
# совпадению всего вывода: `kimi -p` печатает ход рассуждения рядом с ответом, и сравнение
# целиком объявляло бы находкой любой честный «OK».
#
# Упавший снайпер = не пройденная проверка (та же воронка, что у остальных гейтов).
set -uo pipefail

. "$(dirname "${BASH_SOURCE[0]}")/lib-hooks.sh"
CMD=$(hook_command)
is_git_commit "$CMD" || { echo '{}'; exit 0; }

cd_repo || { hook_ask "Хук $(basename "$0") не смог определить каталог репозитория и ничего не проверил. Пропускать проверку молча нельзя."; exit 0; }

OUT=".claude/state/staged-kimi.diff"
mkdir -p .claude/state 2>/dev/null

# Проверяем ровно то, что уйдёт в коммит: при пат-спеке — только названные пути.
mapfile -t PS < <(hook_commit_pathspec "$CMD")

# 🔴 ГРАФ ИЗ РЕВЬЮ ИСКЛЮЧЁН (11.08). Каждый кодовый коммит обязан нести
# memory_bank/mcp-memory.json (гейт check-graph-fresh), а его строки JSONL длинные:
# граф раздувал дифф снайпера до ~200 КБ, и модель не укладывалась в таймаут — пять
# коммитов остановлены с кодом 124. Находки снайпера — про исполняемый код; граф —
# данные, и их проверяет детерминированный гейт, а не модель. Меньше дифф — короче ответ.
EXCL=':!memory_bank/mcp-memory.json'
if ! git diff --cached -- "${PS[@]}" "$EXCL" > "$OUT" 2>/dev/null; then
  printf 'ДИФФ НЕ СНЯТ: git diff --cached не отработал. Проверку считать невыполненной.\n' > "$OUT"
elif [ ! -s "$OUT" ]; then
  if [ -n "$(git diff --cached --name-only -- "${PS[@]}" 2>/dev/null)" ]; then
    # Индекс не пуст, но после исключения графа кода нет: модель звать незачем.
    hook_log "sniper-kimi" "пропуск: в коммите только граф (не код) — ревью не нужно"
    echo '{}'; exit 0
  fi
  # Хук движка срабатывает ДО всей команды: на `git add … && git commit …` индекс ещё
  # пуст, и «пусто» означало бы «чисто», ничего не посмотрев.
  printf 'ДИФФ НЕ СНЯТ: индекс пуст на момент проверки.\nСкорее всего `git add` идёт той же командой, что и коммит: хук движка отрабатывает ДО неё.\nСделай `git add` отдельной командой, затем коммит — тогда проверка увидит то, что уедет в историю.\n' > "$OUT"
fi

if head -1 "$OUT" | grep -q 'ДИФФ НЕ СНЯТ'; then
  hook_log "sniper-kimi" "🔴 дифф не снят — вердикта нет"
  hook_stop "sniper-kimi" "Снайпер не получил дифф и не может подтвердить чистоту коммита:

$(cat "$OUT")
Молчаливое «OK» без проверки — ложь, поэтому вердикта нет."
  exit 0
fi

# Зов модели. SNIPER_KIMI_CMD — шов для пробы: без сервера и модели подставляется stub
# с той же формой вызова. В работе переменная не задана и зовётся настоящий kimi.
SNIPER="${SNIPER_KIMI_CMD:-kimi}"
PROMPT='Ты снайпер на страже коммита. Дифф лежит в файле .claude/state/staged-kimi.diff в текущем каталоге — ПРОЧИТАЙ ЭТОТ ФАЙЛ инструментом чтения файла. Не вызывай оболочку и не собирай дифф сам. Ничего не меняй, на сервер не ходи.

Найди в ДОБАВЛЕННЫХ строках (начинаются с +) только эти пять вещей:
1) ВЕЛОСИПЕД: свой SQL или свой алгоритм там, где у SereneDB есть штатный механизм (свой цикл вместо ts_compound, свои счётчики вместо ts_dict_*, свой ts_like вместо sparse_ngram, свой отбор списком вместо отбора в базе). Правило владельца: своё пишем только после ответа агента serenedb-native «штатного нет».
2) ПОДГОНКА: числовая отсечка в пути ПРАВИЛЬНОСТИ (сколько кандидатов, какой порог, какое расстояние), подобранная под нашу базу. Бюджеты скорости/памяти (размер пачки, параллельность, LIMIT показа) — НЕ находка.
3) РОСТ: величина, уходящая в LLM или в память, которая растёт с числом таблиц/строк/колонок и не ограничена сверху.
4) ИМЯ НАШЕЙ БАЗЫ: имя сущности/реквизита/контрагента конкретной базы 1С в исполняемом коде.
5) ОБВЯЗКА ПОВЕРХ OPENCLAW: самописный инструмент, канал, обработчик сообщений или конфигурация рядом с OpenClaw там, где у установленной сборки есть штатный механизм (своя отправка в Telegram вместо канала OpenClaw, свой планировщик вместо его расписаний, свой плагин вместо его инструментов). Доки установленной сборки — /usr/lib/node_modules/openclaw/docs; /opt/openclaw-engine — доки СЛЕДУЮЩЕЙ версии, отвечать «есть ли у нас» по ним нельзя. Правило владельца 26.07: своё поверх OpenClaw — только после ответа агента openclaw-native «штатного нет».

Форма ответа строго: если ничего из пяти нет — последней строкой выведи ровно «VERDICT: OK».
Если находки есть — по каждой одна строка, начинающаяся ровно с «FINDING: » (например: FINDING: файл:строка — что именно — чем чинить), а последней строкой ровно «VERDICT: FINDINGS». Без предисловий.'

hook_log "sniper-kimi" "зов модели ($(wc -c < "$OUT") байт диффа)"
# 🔴 Таймаут зова — 570 с при потолке хука 600 (конфиг Kimi): ревью большого диффа при
# медленном API стоит 3–5+ минут (замеры 11.08: 100 строк — 67 с, полный промт не
# закончился за 280 с). Калибровка 180 с была снята на быстром API и превратила гейт в
# постоянную остановку (код 124). Упавший по таймауту снайпер — по-прежнему не пройденная
# проверка: люк рассчитан на разовую ошибку, а не на «модель медленнее таймаута».
VERDICT=$(timeout 570 "$SNIPER" -p "$PROMPT" 2>/dev/null)
rc=$?

if [ "$rc" -ne 0 ] || [ -z "$VERDICT" ]; then
  hook_log "sniper-kimi" "🔴 снайпер не отработал (код $rc)"
  hook_stop "sniper-kimi" "Снайпер коммита не отработал (код $rc): модель не ответила.
Упавшая проверка — не пройденная проверка: коммит остановлен, пока снайпер не заработает.
Проверь, что из-под рабочего аккаунта отвечает \`kimi -p\` (вход, сеть, квота)."
  exit 0
fi

# 🔴 Маяк ищется НЕ от начала строки: `kimi -p` печатает ответ со служебной разметкой, и
# форма меняется от прогона к прогону (живые прогоны 06.08: «  VERDICT: OK», затем
# «• VERDICT: OK»). Поэтому берётся ПОСЛЕДНИЙ маяк в выводе: инструкция требует вердикт
# последней строкой, а упоминания формата в рассуждении стоят раньше и перекрываются.
MARK=$(printf '%s\n' "$VERDICT" | grep -oE 'VERDICT:[[:space:]]*(OK|FINDINGS)' | tail -1)
# 🔴 Сжатие пробелов — ОТДЕЛЬНЫМ шагом и без перевода строки на входе: tr в общем
# конвейере превращал перевод строки в концевой пробел («VERDICT: OK »), и сравнение
# с маяком не сходилось — чистый вердикт читался как неразобранный (проба 06.08).
MARK=$(printf '%s' "$MARK" | tr -s '[:space:]' ' ')

if [ "$MARK" = "VERDICT: OK" ]; then
  hook_log "sniper-kimi" "OK"
  echo '{}'
  exit 0
fi

if [ "$MARK" = "VERDICT: FINDINGS" ]; then
  hook_log "sniper-kimi" "СТОП (находки)"
  # 🔴 Находки извлекаются по префиксу FINDING:, а не «хвостом вывода»: в stdout
  # `kimi -p` рядом с ответом лежат и вброс движка (UserPromptSubmit печатает его в
  # stdout вложенной сессии), и ход рассуждения — `tail` по всему выводу клал в причину
  # остановки чужой текст вместо находок (живой прогон 06.08).
  FINDINGS=$(printf '%s\n' "$VERDICT" | grep -oE 'FINDING:[[:space:]].*' | tail -10)
  [ -z "$FINDINGS" ] && FINDINGS="(модель не оформила находки префиксом FINDING:)
$(printf '%s\n' "$VERDICT" | grep -vE 'VERDICT:' | tail -8)"
  hook_stop "sniper-kimi" "Снайпер коммита — находки:

$FINDINGS

Исправь или объясни. Находка ложная — скажи почему и закрой гейт штатно:
пометкой в коммите либо через владельца (люк)."
  exit 0
fi

# Ответ есть, но маяка нет: модель ушла в рассуждение. Вердикт не разобран = проверка
# не выполнена, а не пройдена.
hook_log "sniper-kimi" "🔴 вердикт не разобран"
hook_stop "sniper-kimi" "Снайпер ответил без строки вердикта — проверку считать невыполненной.
Повтори коммит; при повторе — разбирайся с вызовом модели в sniper-kimi.sh."
