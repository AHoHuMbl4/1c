#!/usr/bin/env bash
# Гейт коммита — вся логика. Живёт в `.claude/hooks/`, потому что этот каталог среда
# закрывает на запись даже из оболочки («destructive hook entrypoint»): проверено пробой
# 03.08 — и `Write`, и `printf > файл` отбиты. `.githooks/pre-commit` остаётся тонкой
# обёрткой, которая только зовёт этот файл.
#
# 🔴 ЗАЧЕМ ТАК. До 03.08 гейт целиком лежал в `.githooks/`, куда сессия писать может.
# Правило, которое исполнитель вправе переписать, — не правило, а пожелание с лишним
# шагом. Теперь наоборот: обёртка беззащитна, но бессодержательна, а содержательная часть
# недоступна на запись. Порча обёртки ловится с ДВУХ сторон:
#   * этот файл сверяет обёртку при каждом коммите;
#   * хук движка `check-gates.sh` сверяет её при каждом коммите из сессии.
# Оба живут в защищённом каталоге.
#
# Здесь только детерминированные проверки (молчат, пока правило не нарушено).
# Аварийный люк: `git commit --no-verify` — он виден в истории команд и не тихий.
set -uo pipefail
cd "$(git rev-parse --show-toplevel)" || exit 0
LOG=".claude/hooks.log"
log() { printf '%s %-11s %s\n' "$(date '+%d.%m %H:%M:%S')" "git-gate" "$1" >> "$LOG" 2>/dev/null || true; }

STAGED=$(git diff --cached --name-only)
[ -z "$STAGED" ] && exit 0

# Трек владельца (решение 02.08, owner-memory): установщик коммитится из Cursor,
# коммит целиком из windows/odata-setup не проверяем.
if ! printf '%s\n' "$STAGED" | grep -qv '^windows/odata-setup/'; then
  log "пропуск: трек владельца (odata-setup)"
  exit 0
fi

fail=0
say() { { echo; echo "== $1 =="; printf '%s\n' "$2"; } >&2; fail=1; }

# ── 1. Гейты не разоружены ───────────────────────────────────────────────────────────
# Проверяется СОСТОЯНИЕ, а не дифф: неважно, кто и когда снял защиту — коммит не уйдёт,
# пока она снята. Это и есть разница между «нельзя обойти» и «нельзя обойти незаметно».
. .claude/hooks/lib-hooks.sh 2>/dev/null || true
if declare -f hook_guard_armed >/dev/null 2>&1; then
  BROKEN="$(hook_guard_armed)"
  [ -n "$BROKEN" ] && say "защита гейтов" "$BROKEN
Верните защиту на место — или снимайте её отдельным коммитом с объяснением владельцу."
else
  say "защита гейтов" "В .claude/hooks/lib-hooks.sh нет hook_guard_armed — проверить целость гейтов нечем.
Похоже, библиотека хуков подменена или не установлена."
fi

# ── 2. Люк не оставлен открытым ──────────────────────────────────────────────────────
OVR=".claude/hooks/override.txt"
if [ -s "$OVR" ]; then
  say "аварийный люк" "Файл люка не пуст:
$(sed 's/^/  /' "$OVR")
Люк открывает и снимает владелец — файл лежит в защищённом каталоге, сессия туда не
пишет. Строка не потребляется хуком, поэтому единственное, что удерживает дверь от
того, чтобы остаться открытой навсегда, — вот эта остановка: пока файл не пуст,
коммита не будет. Уберите строку и коммитьте."
fi

# ── 3. Сами проверки ────────────────────────────────────────────────────────────────
# 🔴 Полный набор, а не только «дешёвые»: правило, которое проверяется лишь в сессии с
# хуками движка, не работает у владельца, в Cursor и в дочерней сессии.
# 🔴 ДВА ЗАХОДА, ПОТОМУ ЧТО СООБЩЕНИЕ ПОЯВЛЯЕТСЯ ПОЗЖЕ ИНДЕКСА. `pre-commit` вызывается
# «before obtaining the proposed commit log message» (man githooks), поэтому пометку
# «Доки:» / «Числа:» там взять негде — в `.git/COMMIT_EDITMSG` лежит прошлый коммит.
# Проверки, которые этой пометкой закрываются, гейт запускает из `commit-msg`, куда git
# передаёт файл сообщения первым доводом. Поймала рабочая сессия, не проба: она честно
# назвала раздел доков в коммите, а гейт со стороны git его не увидел.
if [ -n "${1:-}" ] && [ -f "${1:-}" ]; then
  export HOOK_MSG_FILE="$1"
  # check-gold-split закрывается пометкой «Факт 1С:» — только здесь сообщение видно.
  GATES="check-sql-docs check-diff check-gold-split"
else
  GATES="check-docs check-graph-fresh check-active-size check-prompt-rules check-live-probe"
fi

FAKE='{"tool_input":{"command":"git commit"}}'
for h in $GATES; do
  # 🔴 Упавшая проверка — не пройденная проверка. Прежде здесь стояло `|| continue`:
  # хук, который не запустился (нет файла, нет python3, синтаксическая ошибка), молча
  # пропускал коммит — тот же fail-open, ради которого этот гейт и заводился.
  out=$(printf '%s' "$FAKE" | ".claude/hooks/$h.sh" 2>/dev/null)
  rc=$?
  if [ "$rc" -ne 0 ]; then
    say "$h" "проверка не отработала (код $rc). Молча пропускать нельзя: почини хук
или обойди осознанно — git commit --no-verify"
    continue
  fi
  reason=$(printf '%s' "$out" | python3 -c "
import json, sys
try:
    d = json.load(sys.stdin)
except Exception:
    sys.exit(0)
r = (d.get('hookSpecificOutput') or {}).get('permissionDecisionReason') or ''
print(r)")
  [ -n "$reason" ] && say "$h" "$reason"
done

if [ "$fail" -eq 1 ]; then
  log "БЛОК коммита"
  { echo; echo "Коммит остановлен гейтом git (.githooks/pre-commit → .claude/hooks/git-gate.sh)."
    echo "Поправь и повтори. Осознанный обход, если проверка ошибается: git commit --no-verify"; } >&2
  exit 1
fi
log "ok"
exit 0
