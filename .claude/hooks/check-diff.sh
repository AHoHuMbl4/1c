#!/usr/bin/env bash
# Перехват перед коммитом: ищет в диффе то, что подгоняется под конкретную базу.
#
# Зачем: агенты-контролёры — рецензенты, их зовут вручную и постфактум. Между вызовами
# можно спокойно подобрать константу под свой набор вопросов и закоммитить. Этот хук
# срабатывает без чьего-либо решения.
#
# Ловит:
#   * новые числовые константы в исполняемом коде (не в комментариях);
#   * кириллические литералы в коде — вероятные имена сущностей конкретной базы;
#   * промт-правила вида «никогда/всегда» там, где нужен код.
# Находки не блокируют, а выносятся владельцу: решение за ним.
set -uo pipefail

# Хук навешен на Bash целиком: отбор команды делаем здесь, чтобы не зависеть от
# того, поддерживается ли поле `if` в этой сборке.
. "$(dirname "${BASH_SOURCE[0]}")/lib-hooks.sh"
CMD=$(hook_command)
# Опознаватель общий на все хуки (`lib-hooks.sh`): подстрока «git commit» пропускала
# равнозначные формы вроде `git -C /srv/1c commit` (`F248`).
is_git_commit "$CMD" || { echo '{}'; exit 0; }

# Корень репозитория — от движка или от места самого хука, НЕ от текущего каталога:
# прежняя форма при запуске из чужого каталога молча пропускала коммит (fail-open).
cd_repo || { hook_ask "Хук $(basename "$0") не смог определить каталог репозитория и ничего не проверил. Пропускать проверку молча нельзя — подтвердите шаг вручную."; exit 0; }

DIFF=$(git diff --cached -U0 -- '*.py' '*.js' '*.mjs' 2>/dev/null)
[ -z "$DIFF" ] && { echo '{}'; exit 0; }

ADDED=$(printf '%s\n' "$DIFF" | grep '^+' | grep -v '^+++' | sed 's/^+//')
# Строки-комментарии и документацию не разбираем: там числа и имена уместны.
CODE=$(printf '%s\n' "$ADDED" | grep -vE '^\s*(#|//|\*|"""|\x27\x27\x27)' | sed 's/#.*$//; s|//.*$||')

FINDINGS=""

NUMS=$(printf '%s\n' "$CODE" \
  | grep -oE '=\s*[0-9]+(\.[0-9]+)?\b' \
  | grep -oE '[0-9]+(\.[0-9]+)?' \
  | grep -vE '^(0|1|2|100|1000)$' | sort -u | head -8)
[ -n "$NUMS" ] && FINDINGS="${FINDINGS}Новые числовые константы: $(printf '%s' "$NUMS" | tr '\n' ' ')
Каждая обязана быть либо параметром бюджета (влияет на скорость/объём), либо иметь
обоснование замером. Подобранная под наш набор вопросов — дефект.
"

CYR=$(printf '%s\n' "$CODE" | grep -oE '"[^"]*[А-Яа-яЁё][^"]*"|\x27[^\x27]*[А-Яа-яЁё][^\x27]*\x27' \
  | grep -vE 'ошибк|Ошибк|ВНИМАНИЕ|FATAL|перепись|витрина|строк|сущност|индекс|корпус|нет данных|Найдено' \
  | sort -u | head -5)
[ -n "$CYR" ] && FINDINGS="${FINDINGS}Кириллица в коде: $(printf '%s' "$CYR" | tr '\n' ' ')
Если это имя сущности или реквизита конкретной базы — на чужой базе не сработает.
"

PROMPT=$(printf '%s\n' "$CODE" | grep -icE 'never |always |do not |не выдумывай|никогда не' || true)
[ "${PROMPT:-0}" -gt 0 ] && FINDINGS="${FINDINGS}В диффе ${PROMPT} правил-указаний модели. Промт не является гарантией:
всё обязательное держится кодом.
"

if [ -z "$FINDINGS" ]; then echo '{}'; exit 0; fi

python3 - "$FINDINGS" <<'PY' | hook_gate_json check-diff
import json, sys
print(json.dumps({"hookSpecificOutput": {
    "hookEventName": "PreToolUse",
    "permissionDecision": "deny",
    "permissionDecisionReason": "Проверка коммита нашла возможную подгонку под нашу базу:\n\n"
                               + sys.argv[1]
                               + "\nЕсли обосновано — подтвердите; если нет — правьте до коммита."}},
    ensure_ascii=False))
PY
