#!/bin/bash
# Разложить скрипты сборки из репозитория в рабочий каталог, откуда их запускает systemd.
#
# 🔴 ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ «скопировать руками». [замер 28.07] починка SQL была
# закоммичена, но не скопирована в `/opt/1c-mcp-reports` — и сборка чужой базы полтакта
# шла по СТАРЫМ файлам. Симптом при этом выглядел как дефект кода, которого в коде уже не
# было. Копирование руками — шаг, который можно забыть; значит, его быть не должно
# (`PLAN_AUTONOMY`, перечень ручного).
#
# Копирует ТОЛЬКО то, что отличается, и печатает что именно, — чтобы в журнале такта было
# видно, менялся ли исполняемый код между тактами.
#
# Использование: deploy.sh [каталог-назначения]   (по умолчанию /opt/1c-mcp-reports)
set -eu
SRC="$(cd "$(dirname "$0")" && pwd)"
DST="${1:-${SERENE_DEPLOY_DIR:-/opt/1c-mcp-reports}}"

[ -d "$DST" ] || { echo "нет каталога назначения: $DST" >&2; exit 1; }

changed=0
for f in "$SRC"/*.sh "$SRC"/*.sql "$SRC"/*.py "$SRC"/*.tsv; do
  [ -e "$f" ] || continue
  b="$(basename "$f")"
  [ "$b" = "deploy.sh" ] && continue
  if ! cmp -s "$f" "$DST/$b"; then
    # 🔴 ПОДМЕНА АТОМАРНАЯ, А НЕ ЗАПИСЬ ПОВЕРХ. `bash` дочитывает скрипт по ходу
    # исполнения, поэтому запись в тот же inode на лету рвёт идущий такт в произвольном
    # месте. `mv` в пределах каталога меняет только ссылку: у работающего процесса
    # остаётся прежний файл, а следующий запуск берёт новый.
    install -m "$( [ -x "$f" ] && echo 755 || echo 644 )" "$f" "$DST/.$b.new"
    mv -f "$DST/.$b.new" "$DST/$b"
    echo "  обновлён: $b"
    changed=$((changed + 1))
  fi
done

if [ -d "$SRC/ask" ]; then
  mkdir -p "$DST/ask"
  for f in "$SRC/ask"/*.py; do
    [ -e "$f" ] || continue
    b="ask/$(basename "$f")"
    if ! cmp -s "$f" "$DST/$b"; then
      install -m 644 "$f" "$DST/.$b.new"
      mv -f "$DST/.$b.new" "$DST/$b"
      echo "  обновлён: $b"
      changed=$((changed + 1))
    fi
  done
fi

echo "{\"развёрнуто_в\":\"$DST\",\"обновлено_файлов\":$changed}"
