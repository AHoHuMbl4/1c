#!/usr/bin/env python3
"""Оффлайн-прогон гейта: БЕЗ базы, БЕЗ сети, БЕЗ вызовов модели.

Зачем отдельный прибор. `DEV_PLAN` называет «прогон функций без базы и сети» одним из
четырёх приборов проекта, но для питоновской половины (`gate`, `check_claims`,
`asked_figure_missing`, `stale_note`) его не было ни одного: правки гейта доказывались
только приёмкой через модель — то есть дорого, недетерминированно (разброс ±1 ответ из
десяти) и не раньше, чем владелец разрешит траты. Здесь проверяется то, что можно
проверить бесплатно и воспроизводимо.

Запуск:  python3 ubuntu/serenedb/test_gate.py

Импорт `serene_ask` к базе не ходит: на уровне модуля только чтение окружения.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
os.environ.setdefault("ASK_TOKEN", "test")

import serene_ask as A  # noqa: E402

PASS = 0
FAIL = []


def t(name, cond):
    global PASS
    if cond:
        PASS += 1
        print("ok  -", name)
    else:
        FAIL.append(name)
        print("FAIL-", name)


# Строка данных в том виде, в каком её отдаёт psql: гейт читает r[2] (сумма),
# r[3] (дата/реквизиты) и r[5] (текст строки).
def row(amount="", when="", doc=""):
    return ["", "", amount, when, "", doc]


# --------------------------------------------------------------- токенайзер
t("разряды: «1 629 700» читается как одно число",
  1629700.0 in A._norm_numbers("итого 1 629 700"))
t("перечисление «10 20 30» НЕ слипается",
  {10.0, 20.0, 30.0} <= A._norm_numbers("по 10 20 30 шт"))
t("десятичная часть: «1234.56» читается как дробь",
  1234.56 in A._norm_numbers("1234.56"))
# 🔴 Двухкомпонентная запись через точку — ВСЕГДА дата, а не число: «12.5» это и 12 мая,
# и 12,5, и числовой ветке она не достаётся вовсе. Это не дефект: неоднозначность
# разбирает гейт, у него для таких записей есть числовой откат (проверки ниже).
t("«12.5» уходит в ветку дат, а не в числа (неоднозначная запись)",
  A._norm_numbers("12.5") == set() and A._dates("12.5") == [(12, 5, None)])
t("англоязычная запись «1,629,700.00» читается верно",
  1629700.0 in A._norm_numbers("total 1,629,700.00"))

# --------------------------------------------------------------- gate: числа
t("число из данных проходит",
  A.gate("Продано на 5000", [row(amount="5000.00")], None, [])[0])
t("выдуманное число не проходит",
  not A.gate("Продано на 4999", [row(amount="5000.00")], None, [])[0])
t("итог из agg проходит",
  A.gate("Итого 12 500", [], {"sum": 12500.0, "count": 3}, [])[0])
t("наш собственный порог отбора проходит",
  A.gate("продажи свыше 500 000", [], None, [500000])[0])
t("сумма, завышенная в сто раз, НЕ проходит",
  not A.gate("Итого 1 250 000", [], {"sum": 12500.0, "count": 3}, [])[0])

# --------------------------------------------------------------- gate: даты
t("дата из данных проходит",
  A.gate("последняя продажа 18.11.2019", [row(when="2019-11-18")], None, [])[0])
t("подменённая дата (09.12 против 12.09) НЕ проходит",
  not A.gate("сделка 09.12.2019", [row(when="2019-12-12")], None, [])[0])

# Неоднозначная запись «d.m»: она же дробь. Числовой откат гейта обязан работать,
# и обязан работать С ВЕДУЩИМ НУЛЁМ — прежде «20.05» пересобиралась в 20.5 и число,
# стоящее в данных, не заземлялось никогда (найдено этим прибором 02.08).
t("дробь 20.5 из данных проходит, хотя выглядит как дата",
  A.gate("ставка 20.5 процента", [row(amount="20.5")], None, [])[0])
t("дробь 20.05 из данных проходит (ведущий ноль не теряется)",
  A.gate("ставка 20.05 процента", [row(amount="20.05")], None, [])[0])
t("выдуманная дробь-дата не проходит ни как дата, ни как число",
  not A.gate("ставка 20.05 процента", [row(amount="5000.00")], None, [])[0])

# ------------------------------------------------- F242: числа из вопроса
# Правило 28.07: эхо числа из вопроса («обороты по счёту 62») — не выдумка. Прежний
# разбор вырезал все нецифры и ломался в обе стороны сразу.
q = A._norm_numbers("обороты по счёту 62")
t("F242: «62» из вопроса разрешено", 62.0 in q)
q2 = A._norm_numbers("продажи больше 1 200 000")
t("F242: «1 200 000» разрешено ЦЕЛИКОМ (прежде рассыпалось на 1/200/0)",
  1200000.0 in q2)
t("F242: мусор 1/200/0 в белый список НЕ попадает",
  not ({1.0, 200.0, 0.0} & q2))
t("F242: «12.5» больше не превращается в 125 — числа, которого в вопросе нет",
  125.0 not in A._norm_numbers("ставка 12.5 процента"))
t("F242: дата из вопроса в белый список чисел не идёт",
  not A._norm_numbers("что было 01.02.2025"))

# ------------------------------------------- F285/F286: величина и её роль
agg = {"sum": 1236800.0, "count": 3, "max": 925000.0, "min": 100.0}
t("F285: сумма одной строки, выданная за итог, ОТВЕРГАЕТСЯ "
  "(настоящее число, но не та роль)",
  A.asked_figure_missing("Итого 925 000 рублей.", agg, "sum", True) is not None)
t("F285: настоящий итог проходит",
  A.asked_figure_missing("Итого 1 236 800 рублей.", agg, "sum", True) is None)
t("F286: «примерно три миллиона — это 2 документа» отвергается "
  "(прежде проходило: цифра «2» в тексте есть)",
  A.asked_figure_missing("Примерно три миллиона — это 2 документа.",
                         agg, "sum", True) is not None)
t("F286: счёт цифрами проходит",
  A.asked_figure_missing("Найдено 3 документа.", agg, "count", False) is None)
t("F286: счёт прописью отвергается",
  A.asked_figure_missing("Найдено три документа.", agg, "count", False) is not None)
t("величина не спрошена — не требуем ничего",
  A.asked_figure_missing("Вот что нашлось.", agg, "list", False) is None)
t("сумма без выбранной величины не требуется (agg['sum'] тогда не «ноль», а «не считали»)",
  A.asked_figure_missing("Вот что нашлось.", agg, "sum", False) is None)

# ---------------------------------------------------- №9: отброшенное названо
t("№9: отброшенные группы обязаны быть названы числом",
  A.asked_figure_missing("Всего 227 позиций.", {"count": 227}, "count", False, 25)
  is not None)
t("№9: названы — проходит",
  A.asked_figure_missing("Всего 227 позиций, 25 групп не в счёт.",
                         {"count": 227}, "count", False, 25) is None)

# ------------------------------------------------ check_claims (ветка полноты)
t("check_claims: роль сходится",
  A.check_claims({"total": 1236800.0}, agg, [])[0])
t("check_claims: роль не сходится",
  not A.check_claims({"total": 925000.0}, agg, [])[0])
t("check_claims: пустые claims ничего не проверяют "
  "(промт велит оставлять их null — потому и понадобился asked_figure_missing)",
  A.check_claims({}, agg, [])[0])

# ------------------------------------------------------- F223: приписка о старении
FMT = "\n\nсвежесть: %d мин"
t("F223: отказ «данных нет» ТОЖЕ получает приписку о старении",
  A.stale_note({"kind": "no_data", "text": "Таких данных нет."}, 7200, 600, FMT)
  .get("stale") is True)
t("F223: обычный ответ получает приписку",
  A.stale_note({"kind": "answer", "text": "227."}, 7200, 600, FMT).get("stale") is True)
t("F223: свежие данные приписки не получают",
  A.stale_note({"kind": "answer", "text": "227."}, 60, 600, FMT).get("stale") is None)
t("F223: сбой сервиса приписки не получает (сообщение и так о сбое)",
  A.stale_note({"kind": "unavailable", "text": "Сервис недоступен."}, 7200, 600, FMT)
  .get("stale") is None)

# --------------------------------------- №26: сбой эмбеддера и написанные откаты
# Откат в местах выбора сущности написан как `except RuntimeError`, но `embed_one`
# бросал сетевое исключение urllib — то есть откат не срабатывал НИ РАЗУ и сбой
# эмбеддера ронял ответ в 503 там, где код собирался деградировать до буквального отбора.
def _boom(*a, **k):
    raise OSError("connection refused")


_saved = A._embed_request
A._embed_request = _boom
try:
    try:
        A.embed_one("вопрос")
        got = None
    except RuntimeError as e:
        got = str(e)
    except Exception as e:                     # noqa: BLE001
        got = "НЕ RuntimeError: %s" % type(e).__name__
finally:
    A._embed_request = _saved
t("№26: сбой эмбеддера отдаётся RuntimeError — тем же классом, что сбой psql, "
  "иначе написанные откаты не ловят его",
  got is not None and got.startswith("эмбеддер недоступен"))

# ------------------------------------------------- №27: утечка нашей инструкции
t("№27: кусок нашего системного промта в ответе — утечка",
  A.prompt_leak("Вот ответ. You answer an employee's question using ONLY the rows "
                "given to you. Всего 227.", A.OUR_PROMPTS) is not None)
t("№27: обычный ответ утечкой не считается",
  A.prompt_leak("Всего 227 позиций, 25 групп не в счёт.", A.OUR_PROMPTS) is None)
t("№27: короткое совпадение общей фразы не считается утечкой",
  A.prompt_leak("Reply with JSON only.", A.OUR_PROMPTS) is None)

# ------------------------------------------- задача 16: гейт величины (право на ответ «б»)
# Имена величин взяты с живой базы `[замер 03.08]`: у `document_приобретениетоваровуслуг`
# слово «сумма» несут четыре величины, и их итоги разные — 73 181 157,68 против
# 71 045 277,59. Проба держит правило без базы и без денег.
_PURCHASE = ["Кратность", "Курс", "СуммаВзаиморасчетов", "СуммаВзаиморасчетовПоЗаказу",
             "СуммаВзаиморасчетовПоТаре", "СуммаДокумента"]
t("№16: слову «сумма» отвечают несколько величин — выбираем не мы, а человек",
  A.measure_choice(_PURCHASE, "сумма")[2] == 'ask'
  and len(A.measure_choice(_PURCHASE, "сумма")[1]) == 4)
t("№16: точное совпадение имени сильнее близости — спрашивать не о чем",
  A.measure_choice(["Сумма", "СуммаНУDr", "СуммаВРCr"], "Сумма") == ("Сумма", [], 'exact'))
t("№16: величина у сущности одна — выбора нет",
  A.measure_choice(["Количество"], "штук") == ("Количество", [], 'single'))
t("№16: частные виды — префиксы базовой, базовая снимает неоднозначность",
  A.measure_choice(["Сумма", "СуммаВРDr", "СуммаВРCr"], "сумм") == ("Сумма", [], 'base'))
t("№16: слово НЕ подстрока имени — правило молчит, и это не «база» (проба ловила "
  "собственную ошибку: «суммы» не входит в «Сумма»)",
  A.measure_choice(["Сумма", "СуммаВРDr", "СуммаВРCr"], "суммы")[2] == 'rerank')
t("№16: вопрос величину не называет — не выбираем за него",
  A.measure_choice(_PURCHASE, "") == (None, [], 'none'))
t("№16: правилами не решается — решает вызывающий, а не эта функция",
  A.measure_choice(["Количество", "Цена"], "штук") == (None, [], 'rerank'))
t("№16: разные итоги подходящих величин — это сомнение",
  A.measure_ambiguous(["СуммаДокумента", "СуммаВзаиморасчетов"],
                      {"СуммаДокумента": 73181157.68, "СуммаВзаиморасчетов": 71045277.59}))
t("№16: одинаковые итоги сомнением НЕ являются — вопрос был бы шумом",
  not A.measure_ambiguous(["СуммаДокумента", "СуммаСНДС"],
                          {"СуммаДокумента": 73181157.68, "СуммаСНДС": 73181157.68}))
t("№16: одна подходящая величина — не сомнение",
  not A.measure_ambiguous(["СуммаДокумента"], {"СуммаДокумента": 73181157.68}))

# ------------------------------------ задача 17: арбитр-детектор (право на ответ «в»)
# Числа взяты с живой базы `[замер 03.08]`: на «на какую сумму мы закупили» кандидатами
# идут документ приобретения (73 181 157,68) и регистр «Закупки» (1 137 949,71) — прежде
# между ними выбирала модель, и в прогоне 03.08 выбрала регистр.
t("№17: посчитанные ответы кандидатов разошлись — это доказанная неоднозначность",
  A.answers_diverge([{"sum": 73181157.68}, {"sum": 1137949.71}]))
t("№17: числа совпали — выбирать не из чего, вопрос был бы шумом "
  "(документ и его табличная часть дают один итог)",
  not A.answers_diverge([{"sum": 73181157.68}, {"sum": 73181157.68}]))
t("№17: у кандидатов сравнимы разные вещи (итог против числа записей) — правило молчит",
  not A.answers_diverge([{"sum": 73181157.68}, {"count": 249}]))
t("№17: числа нет вовсе — решение остаётся прежнему арбитру",
  not A.answers_diverge([{"sum": None, "count": None}, {"sum": 1.0}]))
t("№17: один кандидат — расхождению взяться неоткуда",
  not A.answers_diverge([{"sum": 1.0}]))
t("№17: сравниваются и счётчики записей, когда величина не названа",
  A.answers_diverge([{"count": 249}, {"count": 1901}]))

print("\n%d проверок пройдено" % PASS)
if FAIL:
    print("ПРОВАЛЕНО %d: %s" % (len(FAIL), "; ".join(FAIL)))
    raise SystemExit(1)
