# ------------------- F247: заземляем на том, что модель ВИДЕЛА, а не на всей выборке
# Гейт разрешал числа из ВСЕХ добытых строк (TOPK=40), тогда как модели показывается
# ROWS_TO_MODEL=25, и каждая ещё режется бюджетом. Числа из непоказанного служили белым
# списком для того, чего модель видеть не могла.
_many = [row(amount="%d.00" % (1000 + i), doc="строка %d" % (1000 + i))
         for i in range(A.ROWS_TO_MODEL + 5)]
_seen = A.rows_seen(_many)
t("F247: показанных строк ровно столько, сколько видит модель",
  len(_seen) == A.ROWS_TO_MODEL)
t("F247: число из НЕпоказанной строки больше не заземляет ответ",
  not A.gate("Итого %d." % (1000 + A.ROWS_TO_MODEL + 2), _seen, None, [])[0])
t("F247: число из показанной строки проходит по-прежнему",
  A.gate("Итого 1000.", _seen, None, [])[0])
# Бюджет делится на число показанных строк, поэтому обрезка видна только когда строк
# много: при одной строке ей отводится весь бюджет и резать нечего.
_per_row = max(320, A.ROWS_BUDGET // A.ROWS_TO_MODEL)
_long = [row(doc="начало" + "." * (_per_row + 50) + "4242")] * A.ROWS_TO_MODEL
t("F247: хвост строки, обрезанный бюджетом, в белый список не идёт",
  not A.gate("Итого 4242.", A.rows_seen(_long), None, [])[0])

# ------------------------------- F248: нумерация пунктов — разметка, а не факт о данных
t("F248: список в начале строк не считается выдумкой",
  A.gate("Итого 5000:\n1. первая\n2. вторая", [row(amount="5000.00")], None, [])[0])
t("F248: перечисление внутри строки — тоже разметка",
  A.gate("Итого 5000: 1) первая, 2) вторая, 3) третья.",
         [row(amount="5000.00")], None, [])[0])
t("F248: число в середине предложения разметкой НЕ считается",
  not A.gate("Итого 5000, из них 47 просрочены.", [row(amount="5000.00")], None, [])[0])
t("F248: длинный номер в середине строки не снимается (это величина, а не пункт)",
  not A.gate("Итого 5000: 103) выдумка.", [row(amount="5000.00")], None, [])[0])

# ------------------------------- F249: отрицательные величины (сторно, возвраты, остатки)
# Минус в числовой токен не входит, поэтому посчитанное базой отрицательное значение
# не совпадало с прочитанным из текста — и верный ответ отвергался.
_neg = {"count": 4, "sum": -1500.5, "min": -70552.79, "max": 1455785.64}
t("F249: наименьшее отрицательное из агрегата проходит",
  A.gate("Наименьшая -70 552.79, наибольшая 1 455 785.64.", [], _neg, [])[0])
t("F249: отрицательный итог проходит и без знака в тексте",
  A.gate("Итого 1 500.50 со знаком минус.", [], _neg, [])[0])
t("F249: выдуманное отрицательное не проходит",
  not A.gate("Наименьшая -70 553.79.", [], _neg, [])[0])
t("F249: отрицательная сумма строки проходит",
  A.gate("Строка на -3.26.", [row(amount="-3.26")], None, [])[0])
t("F250: невозможная дата датой не считается и разбирается как число",
  A._dates("-3.26") == [] and 3.26 in A._norm_numbers("-3.26"))
t("F250: настоящая дата по-прежнему дата, а не число",
  A._dates("18.11.2019") == [(18, 11, 2019)] and A._norm_numbers("18.11.2019") == set())
t("F250: день вне календаря не заземляется чужой датой",
  not A.gate("значение 45.99", [row(when="2019-11-18")], None, [])[0])

print("\n%d проверок пройдено" % PASS)
