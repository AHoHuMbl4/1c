#!/bin/bash
# ЦИКЛ ОБНОВЛЕНИЯ: корпус, резолвер, индекс — штатными средствами SereneDB.
#
# Это то, что запускает таймер вместо `serene_search_build.py`.
#
# Порядок шагов значим:
#   0. развёртывание объектов и проверки ДО такта — они же снимают отпечаток «как было»;
#      секреты — движку нужен токен шлюза 1С (`$metadata` он читает сам) и ключ эмбеддера;
#   1. корпус собирается во временные таблицы и там же сверяется;
#   2. слияние в боевой корпус по отпечатку + публикация индекса;
#      2-бис. разметка сущностей моделью: о чём спрашивают, что служебное;
#   3. векторы МЕТОК сущностей — дёшево (тысячи строк) и нужно для выбора источника;
#   4. резолвер: значения по ключу, векторы только новым;
#   5. векторы КОРПУСА — дороже всего (сотни тысяч строк), поэтому последними и в два
#      прохода: сначала бизнес-сущности, потом всё остальное;
#   6. повторная публикация индекса — досчёт правит `emb` уже после первой;
#   7-8. перепись полноты и проверки ПОСЛЕ такта: сравнение с отпечатком «как было»,
#      такт падает, если данные исчезли; секреты удаляются в любом случае.
#
# 🔴 Почему дешёвое раньше дорогого: первый такт на незнакомой базе идёт часами и может
# оборваться. При прежнем порядке (корпус первым) система всё это время оставалась без
# меток и резолвера — то есть без того, что нужнее для ответа, — считая самое дорогое.
#
# Своего кода в сборке НЕ ОСТАЛОСЬ вовсе: шаг выбора денежной колонки убран вместе с
# самим понятием «денежная колонка» — строка несёт все свои величины, а какую считать,
# решается по вопросу в момент ответа.
set -u
cd "$(dirname "$0")" || exit 1

DSN="${SERENEDB_DSN:-host=127.0.0.1 port=7890 user=postgres dbname=postgres}"
export SERENEDB_DSN="$DSN"
GATE="${ETL_ODATA_BASE:-http://127.0.0.1:6011}"
WORKERS="${BUILD_EMBED_WORKERS:-8}"
# Минимум пула исполнителей для precheck. Умолчание embed_workers+8 (29.07).
# На малой коробке box_tune.sh ставит BUILD_THREAD_MIN=cpu_threads (≤4) — иначе
# precheck не пустит threads=4, а 160 потоков убивает движок (замер 17.08).
THREAD_MIN="${BUILD_THREAD_MIN:-$((WORKERS + 8))}"
# 🔴 МОДЕЛЬ И АДРЕС ЭМБЕДДЕРА ЗАДАЮТСЯ ЯВНО, УМОЛЧАНИЯ НЕТ. Смена модели меняет ВЕКТОРНОЕ
# ПРОСТРАНСТВО: вектор вопроса от одной модели и вектор строки от другой сравниваются без
# всякой ошибки и дают бессмысленную близость — это молчаливая неверность (п. 10, п. 13),
# худший вид отказа. Пока здесь стояло умолчание с именем поставщика, такт мог посчитать
# корпус чужой моделью просто потому, что переменную забыли задать.
EMBED_MODEL="${EMBED_MODEL:-}"
[ -n "$EMBED_MODEL" ] || { echo "СБОРКА ПРЕРВАНА: не задан EMBED_MODEL (модель эмбеддера)" >&2; exit 1; }
EMBED_DIM="${EMBED_DIM:-1024}"
DICT_LOCALE="${SEARCH_DICT_LOCALE:-ru_RU.utf8}"
# 🔴 ОДИН ИСТОЧНИК ПРЕДЕЛА ДЛИНЫ. Строки длиннее него вектор получить не могут; на это
# опираются и досчёт, и проверки до/после такта. Пока число было скопировано в три файла,
# оно могло разойтись молча — и проверка начала бы ждать того, чего не бывает.
EMBED_MAXLEN="${EMBED_MAXLEN:-20000}"; export EMBED_MAXLEN
t0=$(date +%s)

# 🔴 ЗАМОК. Такт идёт минутами, а при первом наполнении — часами; таймер за это время
# успевает выстрелить снова. Два такта на одной таблице выберут ОДНО И ТО ЖЕ множество
# `emb IS NULL` и посчитают его дважды: заплачено дважды, записано дважды. `flock` без
# ожидания — второй просто уходит.
# 🔴 ЗАМОК ИМЕНУЕТСЯ ПО БАЗЕ. Прежде путь был фиксированным, и два конвейера над РАЗНЫМИ
# базами 1С (у клиента их бывает несколько) блокировали друг друга: второй молча уходил,
# и его данные не обновлялись никогда. [найдено 28.07 при тесте на второй базе]
#
# 🔴 ИМЯ БАЗЫ СПРАШИВАЕМ У ДВИЖКА, А НЕ РАЗБИРАЕМ СТРОКУ ПОДКЛЮЧЕНИЯ. Разбор `dbname=`
# регулярным выражением [замер 29.07] развёл по разным замкам два такта над ОДНОЙ базой:
# в окружении конвейера `dbname=` не задан вовсе, libpq подставляет базу по умолчанию, а
# разбор давал `default` — против `postgres` у запуска с явным именем. Два `build.sh`
# пошли одновременно, писали в общие `tmp3_*` и дали 66 дублей ключа. Строка подключения
# знает не всё: имя может прийти из `PGDATABASE`, из файла службы, из URI, а может быть
# опущено. Знает только движок. Ценой одного обращения замок становится верным при любой
# форме DSN.
LOCK_TAG=$(psql "$DSN" -tAc 'SELECT current_database()' 2>/dev/null | tr -cd 'A-Za-z0-9_')
[ -n "$LOCK_TAG" ] || { echo "СБОРКА ПРЕРВАНА: движок не отвечает, имя базы не получено" >&2; exit 1; }
exec 9>/var/lock/1c-serene-build-${LOCK_TAG}.lock
flock -n 9 || { echo "такт уже идёт — этот запуск пропущен"; exit 0; }

# Уборка при ЛЮБОМ выходе, включая обрыв. Прежде секрет удалялся только на штатном пути,
# и после падения посреди такта ключ эмбеддера оставался жить в движке до рестарта.
# `2>/dev/null`, чтобы имя секрета не всплыло в journald в тексте ошибки.
# 🔴 ИМЕНА СЕКРЕТОВ — ПО БАЗЕ. Секреты у движка ОБЩИЕ НА ИНСТАНС, а не на базу: имя
# `qwen` одно на все присоединённые базы. [замер 29.07] сборка второй базы упала, её
# `cleanup` снёс `odg`/`qwen` — и идущий в ту же секунду такт ПЕРВОЙ базы получил
# `ai_embed: secret 'qwen' not found` и остался без векторов. Такт первой базы сломала
# сборка второй, ничего о ней не зная. Та же болезнь, что была с рабочими таблицами
# (`HOW_NOT_TO §3.16`), и лечится так же — отдельными именами, а не аккуратностью.
SEC_ODG="odg_${LOCK_TAG}"

# 🔴 КЛЮЧЕЙ ЭМБЕДДЕРА МОЖЕТ БЫТЬ НЕСКОЛЬКО. [замер 29.07] после того как пул исполнителей
# движка подняли (5-6 → 55 одновременных запросов), скорость выросла лишь вдвое — 9,2 →
# 18,3 строки/с — при НУЛЕ отказов `429`. Значит провайдер не отвергает запросы, а ставит
# их в очередь: отдаёт около двух запросов в секунду на аккаунт, сколько бы мы ни слали.
# Это его потолок, и обойти его можно только вторым аккаунтом.
#
# `EMBED_API_KEYS` — ключи через запятую; если не задана, берётся одиночный
# `EMBED_API_KEY`. Каждому ключу — свой именованный секрет, потоки досчёта раскладываются
# по ним по кругу (`embed_missing.sh`). Несколько ключей нужны были ровно против потолка
# облачного аккаунта; у своего эмбеддера ключ обычно один, и это нормально.
# Прежние имена `ALIBABA_*` читаются как запасные — они остались в старых `/etc/*.env`,
# но имя поставщика в имени настройки было враньём и уходит.
IFS=',' read -r -a _KEYS <<< "${EMBED_API_KEYS:-${EMBED_API_KEY:-${ALIBABA_API_KEYS:-${ALIBABA_API_KEY:-}}}}"
# 🔴 НЕСКОЛЬКО АДРЕСОВ — ПО ОДНОМУ НА КАРТУ, И В ТАКТЕ ТОЖЕ. `EMBED_HOSTS`
# («адрес» или «адрес|ключ», через запятую) заводит по секрету НА АДРЕС — тот же
# разбор, что в `embed_all.sh`. До 13.08 такт строил секреты только по ключам с
# одним `EMBED_HOST`: живой замер на okna-1 — оба воркера в один адрес, GPU 0
# 100%, GPU 1 0%, половина мощности эмбеддера простаивала при верно заполненном
# `EMBED_HOSTS`. Без `EMBED_HOSTS` поведение прежнее: ключи × `EMBED_HOST`.
IFS=',' read -r -a _HOSTS <<< "${EMBED_HOSTS:-${EMBED_HOST:-}}"
[ ${#_HOSTS[@]} -gt 0 ] || _HOSTS=("${EMBED_HOST:-}")
_PAIRS=()
for _h in "${_HOSTS[@]}"; do
  _h="$(printf '%s' "$_h" | tr -d ' ')"
  [ -z "$_h" ] && continue
  case "$_h" in
    *"|"*) _PAIRS+=("$_h") ;;
    *)     for _k0 in "${_KEYS[@]}"; do
             _k0="$(printf '%s' "$_k0" | tr -d ' ')"
             [ -z "$_k0" ] && continue
             _PAIRS+=("$_h|$_k0")
           done ;;
  esac
done
SEC_EMB_LIST=""
for _i in "${!_PAIRS[@]}"; do
  SEC_EMB_LIST="$SEC_EMB_LIST qwen_${LOCK_TAG}_${_i}"
done
SEC_EMB_LIST="${SEC_EMB_LIST# }"
[ -n "$SEC_EMB_LIST" ] || { echo "СБОРКА ПРЕРВАНА: не задан ни один ключ эмбеддера" >&2; exit 1; }
# Первый секрет — для проверок до такта: она дёргает эмбеддер одним запросом.
SEC_EMB="${SEC_EMB_LIST%% *}"
export EMBED_SECRETS="$SEC_EMB_LIST"
cleanup() {
  local _drops="DROP SECRET IF EXISTS $SEC_ODG;"
  for _s in $SEC_EMB_LIST; do _drops="$_drops DROP SECRET IF EXISTS $_s;"; done
  psql "$DSN" -q -c "$_drops" >/dev/null 2>&1
}
trap cleanup EXIT INT TERM HUP

fail() { echo "СБОРКА ПРЕРВАНА: $1" >&2; exit 1; }

# 🔴 ДО ПЕРВОГО ВЕКТОРА: та ли модель. Эндпоинт при неизвестном имени модели молча
# подставляет свою ([замер 02.08]), а векторы разных моделей несравнимы и сравниваются
# без единой ошибки — разбор в `embed_check.sh` и `HOW_NOT_TO §1.39`.
./embed_check.sh || fail "эмбеддер отдаёт не ту модель, которую просим"

echo "== 0. объекты поиска и проверки до такта"
psql "$DSN" -q -v dict_locale="$DICT_LOCALE" -f corpus_init.sql || fail "развёртывание объектов"

# Секреты подаются ФАЙЛОМ с правами 600, а не аргументом командной строки: в командной
# строке они видны любому `ps`. Одинарные кавычки внутри значения удваиваются — иначе
# ключ с апострофом сломал бы синтаксис, и обрывок ключа ушёл бы в текст ошибки.
umask 077
esc() { printf '%s' "${1:-}" | sed "s/'/''/g"; }
SEC=$(mktemp); trap 'rm -f "$SEC"; cleanup' EXIT INT TERM HUP
{
  # 🔴 SCOPE ОБЯЗАТЕЛЕН. [замер 28.07] без него область секрета — `{}`, то есть ВСЕ
  # адреса, и его заголовок `Authorization` перебивает ключ эмбеддера: `ai_embed` уходит
  # в облако с токеном шлюза 1С и получает `HTTP 401 invalid_api_key`.
  # Проверено обоими способами: при `SCOPE '{}'` — 401, при `SCOPE '$GATE'` — вектор 1024,
  # и `read_text('$GATE/$metadata')` при этом продолжает работать (16 652 877 байт).
  # Без этой строки НИ ОДИН вектор за такт не считался бы, а такт заканчивался успехом.
  printf "CREATE OR REPLACE TEMPORARY SECRET %s (TYPE http, SCOPE '%s', EXTRA_HTTP_HEADERS MAP{'Authorization': 'Bearer %s'});\n" "$SEC_ODG" "$GATE" "$(esc "${ODG_GATEWAY_TOKEN:-}")"
  _n=0
  for _s in $SEC_EMB_LIST; do
    printf "CREATE OR REPLACE TEMPORARY SECRET %s (TYPE openai, api_key '%s', base_url '%s', embeddings_path '%s');\n" \
           "$_s" "$(esc "${_PAIRS[$_n]#*|}")" \
           "${_PAIRS[$_n]%%|*}" "$EMBED_PATH"
    _n=$((_n + 1))
  done
} > "$SEC"
# Вывод гасится целиком: при ошибке psql печатает ОПЕРАТОР, а в нём ключ.
psql "$DSN" -q -f "$SEC" >/dev/null 2>&1 || fail "секреты не созданы"
rm -f "$SEC"

# Проверки до такта — после секретов: одна из них дёргает эмбеддер, чтобы убедиться, что
# он жив, ДО того как слияние обнулит векторы у изменившихся строк.
psql "$DSN" -q -v embed_model="$EMBED_MODEL" -v embed_dim="$EMBED_DIM" -v embed_secret="$SEC_EMB" \
     -v embed_workers="$WORKERS" -v embed_maxlen="$EMBED_MAXLEN" -v thread_min="$THREAD_MIN" \
     -f corpus_precheck.sql || fail "проверки до такта"

# ⚠ ЦЕНА ЧЕСТНОСТИ: пропуск теперь срабатывает РЕДКО. Отметку ставит любая полная
# загрузка, а она применяется к 80% источников (дельта требует `Ref_Key`+`DataVersion`).
# Это осознанный выбор: молчаливая потеря свежести дороже лишней пересборки. Чтобы пропуск
# заработал часто и безопасно, нужен дешёвый отпечаток содержимого сущности — тогда полная
# загрузка сможет сказать «данные те же». Записано в PLAN_AUTONOMY как отдельная задача.
#
# 🔴 ПРОПУСК ПЕРЕСБОРКИ, КОГДА СОБИРАТЬ НЕЧЕГО. Вопрос владельца 29.07: «а зачем мы
# постоянно делаем сборку? теряем время». Он прав: за день такт перезапускался четырежды
# ради настроек эмбеддинга, и каждый раз корпус собирался заново — [замер] по 8-18 минут
# холостой работы, больше часа за день.
#
# Пересборка не нужна, если ОДНОВРЕМЕННО:
#   * корпус не пуст;
#   * витрина не менялась с прошлого такта — по отметке `mart_changed_ts` от синка;
#   * не менялся сам `corpus_build.sql` — иначе прежний корпус собран другим кодом.
# Третье условие обязательно: без него правка сборки молча не применялась бы.
#
# Для цели «поставил и работает» это важнее экономии: первый такт на чужой базе идёт
# часами, и без пропуска ЛЮБАЯ остановка — своя или аварийная — отбрасывает в начало.
# 🔴 В ОТПЕЧАТОК ВХОДИТ И ЗАГРУЗЧИК. Он решает, что попадёт в витрину (какие реквизиты
# выигрывают при развороте вложенной формы), поэтому его правка меняет данные так же, как
# правка сборки. Без этого правка загрузчика молча не применялась бы к корпусу: отпечаток
# не изменился — такт пропустил пересборку.
SQL_HASH=$(cat corpus_build.sql poc_load_entity.py 2>/dev/null | md5sum | cut -d' ' -f1)
# 🔴 ПРИЗНАК «ВИТРИНА НЕ МЕНЯЛАСЬ» ДАЁТ СИНК, А НЕ `seen_at`.
# [замер 29.07] `search_sources.seen_at` пишется ТОЛЬКО при первом появлении источника
# (`INSERT … WHERE NOT EXISTS`, `UPDATE` нет ни в одном файле). Это отметка «когда источник
# впервые увидели», а не «когда его данные менялись». Сравнение `build_ts > max(seen_at)`
# после первого же успешного такта давало «пропустить» НАВСЕГДА: новые данные из 1С
# попадали в витрину и никогда не доходили до поиска — молчаливая потеря свежести (п. 17).
#
# Правильный источник — тот, кто знает: синк пишет `mart_changed_ts`, когда что-то залил.
# 🔴 ОТСУТСТВИЕ ОТМЕТКИ = СОБИРАТЬ. Признак недостоверен ⇒ работаем. Иначе забытая отметка
# снова тихо заморозила бы поиск.
# 🔴 ПРОПУСК СВЕРЯЕТСЯ С МОМЕНТОМ ЧТЕНИЯ ВИТРИНЫ, А НЕ С КОНЦОМ ТАКТА.
# `build_ts` пишется постчеком в конце КАЖДОГО такта — и пропущенного тоже. На пакетном
# контуре apply живёт своим таймером, параллельно такту: изменение, применённое ВО ВРЕМЯ
# такта, оказывалось «старше» свежего `build_ts`, и пропуск включался навсегда — [замер
# okna 14.08] витрина 9632, корпус 8199, каждый такт честно писал «не менялись» и делал
# ноль. На деве не стреляло: синк и сборка идут последовательно в одном процессе, во
# время сборки витрину не пишет никто. Поэтому пропуск сверяется с `corpus_built_ts` —
# временем, ЗАФИКСИРОВАННЫМ ДО чтения витрины и записанным только после удачного
# слияния: всё, что легло в витрину позже этого момента (в том числе во время сборки),
# на следующем такте старше отметки и пересоберётся. Отметки нет — собираем.
SKIP_BUILD=$(psql "$DSN" -tA -c "SELECT CASE WHEN
      (SELECT count(*) FROM search_corpus) > 0
  AND (SELECT count(*) FROM search_quality WHERE k='mart_changed_ts') = 1
  AND coalesce((SELECT v FROM search_quality WHERE k='corpus_built_ts'), 0)
      > (SELECT v FROM search_quality WHERE k='mart_changed_ts')
  AND coalesce((SELECT note FROM search_quality WHERE k='build_sql_hash'), '') = '$SQL_HASH'
  -- Временные таблицы сборки нужны ПОСЛЕДУЮЩИМ шагам: резолверу (tmp3_cls, tmp3_ent,
  -- tmp3_src), переписи полноты (tmp3_ent) и разметке сущностей (tmp3_cls). Пропускать
  -- сборку можно, только если они на месте, иначе пропуск уронит следующий шаг.
  AND (SELECT count(*) FROM duckdb_tables()
       WHERE database_name = current_database()
         AND table_name IN ('tmp3_cls','tmp3_ent','tmp3_src','tmp3_corpus')) = 4
  THEN 1 ELSE 0 END" 2>/dev/null)

if [ "${FORCE_REBUILD:-0}" != "1" ] && [ "$SKIP_BUILD" = "1" ]; then
  echo "== 1-2. корпус НЕ пересобирается: данные и код сборки не менялись с прошлого такта"
else
  # Момент ДО чтения витрины: им станет `corpus_built_ts` после удачного слияния.
  # Записывать сразу нельзя — упавшая сборка объявила бы себя состоявшейся, и
  # следующий такт пропустил бы пересборку несобранного.
  BUILD_READ_TS=$(date +%s)

  echo "== 1. корпус: движок читает \$metadata из $GATE и собирает текст"
  psql "$DSN" -q -v gate="$GATE" -f corpus_build.sql || fail "сборка корпуса"

  echo "== 2. слияние в боевой корпус и публикация индекса"
  MERGE_CHUNK_ROWS="${MERGE_CHUNK_ROWS:-1000000}"
  if [ -f ./box_tune.sh ]; then
    # shellcheck disable=SC1091
    . ./box_tune.sh
    _eng_kb="$(box_tune_read_engine_kb)"
    if [ -n "$_eng_kb" ] && [ "$_eng_kb" -gt 0 ]; then
      psql "$DSN" -q -c "INSERT INTO search_quality (k, v, note)
        SELECT 'merge_engine_baseline_kb', ${_eng_kb}::DOUBLE,
               'store.db KiB до первого слияния стейджа'
        WHERE NOT EXISTS (SELECT 1 FROM search_quality WHERE k='merge_engine_baseline_kb');" \
        || fail "отметка merge_engine_baseline_kb"
    fi
    BOX_TUNE_DSN="${BOX_TUNE_DSN:-$DSN}"
    export BOX_TUNE_DSN
    _disk_plan="$(box_tune_disk_preflight)" || fail "префлайт диска (E4b)"
    _cr="$(printf '%s\n' "$_disk_plan" | awk -F= '$1=="merge_chunk_rows"{print $2}')"
    case "$_cr" in ''|*[!0-9]*) ;; *) MERGE_CHUNK_ROWS="$_cr" ;; esac
  fi
  psql "$DSN" -q -c "CREATE OR REPLACE TABLE tmp3_merge_cfg AS SELECT ${MERGE_CHUNK_ROWS}::BIGINT AS chunk_rows;" \
    || fail "конфиг пачек слияния"
  psql "$DSN" -q -f corpus_merge.sql || fail "слияние корпуса"

  psql "$DSN" -q -c "DELETE FROM search_quality WHERE k='corpus_built_ts';
    INSERT INTO search_quality VALUES ('corpus_built_ts', $BUILD_READ_TS,
      'момент чтения витрины последней удавшейся сборкой');" \
    || fail "отметка corpus_built_ts"
fi

