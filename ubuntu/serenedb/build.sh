# 🔴 ДВА ПРОХОДА, А НЕ ОТБОР. Сначала вектор получает то, о чём спрашивают, потом всё
# остальное. Полнота (п. 13) держится тем, что второй проход идёт БЕЗ сужения и покрывает
# все строки, включая служебные; оба прохода обязаны закончиться успехом.
# [замер 29.07, УТ 11.4.9] из 632 683 строк корпуса 167 298 (26%) — замеры времени и
# объекты «Удалить…»: без очерёдности обрыв такта оставлял без вектора то, что нужно, а
# считал то, о чём никто не спросит.
# 🔴 Условие первого прохода — «НЕ названо служебным», а не «названо бизнесом». Разница
# существенна, потому что разметка бывает ЧАСТИЧНОЙ: у неё есть потолок за прогон, и на
# большой базе первые такты знают ещё не про все сущности. При условии «названо бизнесом»
# всё неразмеченное уехало бы во ВТОРОЙ проход — то есть новая сущность ждала бы разметки,
# вместо того чтобы считаться сразу. Ошибка тогда шла бы в сторону «нужное осталось без
# вектора», а допустима только обратная — «посчитали чуть раньше времени».
# 🔴 ВХОД ЭМБЕДДЕРА ОБРЕЗАЕТСЯ, А СТРОКА НЕ ВЫБРАСЫВАЕТСЯ. Прежде сюда уходил `doc`
# целиком, и `embed_missing.sh` исключал из работы всё длиннее предела — то есть строка
# оставалась БЕЗ ВЕКТОРА ВОВСЕ. Пока пределом было 20 000 символов, это касалось 25 строк
# боевой базы; после переезда на свой эмбеддер (контекст 2048 токенов, [замер 02.08]
# 1,84-2,38 символа на токен → предел 3 000) без вектора остались бы 5 845 строк,
# у которых он есть сегодня. Отнимать смысловой поиск у 5 845 строк ради чистоты счёта
# нельзя (п. 13), а вектор по первым 3 000 символам — сигнал неполный, но настоящий:
# сам текст целиком лежит в корпусе и в ТЕКСТОВОМ индексе, по словам он находится весь.
# Сколько строк обрезано — считает `coverage_build.sql` (`cov_emb_cut`), молча это не
# происходит.
echo "== 5. векторы новым строкам корпуса — сначала не-служебные"
