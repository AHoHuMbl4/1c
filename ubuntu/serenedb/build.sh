# 🔴 СЛУЖЕБНЫМ ВЕКТОР НЕ СЧИТАЕТСЯ. Решение владельца 29.07: «да, не нужны они в векторе».
# [замер 29.07, УТ] это 257 966 строк из 632 683 — 41% корпуса: замеры времени платформы
