# такт заканчивался успехом — это ровно тот тихий отказ, из-за которого 20 значений не
# получали вектор КАЖДЫЙ такт и никто не знал (`HOW_NOT_TO §2.10`).
# Разметка «о таком спрашивают / это служебное» — языковой моделью, разово на сущность, с
# кэшем в базе. Нужна ДО векторизации, чтобы задать ей очерёдность. Если модель недоступна,
# разметки просто нет и дальше всё считается одним проходом, как раньше, — поэтому здесь
# предупреждение, а не `fail`: отсутствие приоритета замедляет, но ничего не теряет.
echo "== 2-бис. разметка сущностей (что бизнес, что служебное)"
python3 classify_entities.py || echo "  ВНИМАНИЕ: разметка не удалась, векторы пойдут одним проходом" >&2

# 🔴 ПОРЯДОК ВЕКТОРИЗАЦИИ: ДЕШЁВОЕ И НУЖНОЕ — РАНЬШЕ ДОРОГОГО. Сначала метки сущностей,
# потом резолвер, и только затем корпус. Причина не в экономии, а в том, что первый такт
# на незнакомой базе идёт часами и может оборваться:
#   * метки — [замер 29.07, УТ] 1 501 строка, минуты. Без них не выбрать сущность, когда
#     слова вопроса не совпали дословно;
#   * резолвер — значения измерений, слово человека → значение базы;
#   * корпус — [замер] 632 683 строки, часы. Он самый дорогой и при этом отбор по нему
#     делает BM25, который вектора не требует вовсе.
# Прежний порядок (корпус первым) на большой базе оставлял систему без меток и резолвера
