    echo "  раунд $round: не сдвинулось ни строки — повторять нечем" >&2; break
  fi
  if [ "$round" -ge "$ROUNDS" ]; then
    echo "  достигнут предел раундов ($ROUNDS), осталось $after — доберёт следующий такт" >&2; break
  fi
