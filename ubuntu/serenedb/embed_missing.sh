#!/bin/bash
# Досчитать векторы тем строкам, у которых их нет — штатной функцией движка `ai_embed`.
#
# Почему это shell, а не SQL одним запросом: `ai_embed` САМ группирует строки в пачки, а
# провайдер принимает не больше 10 за раз и не длиннее 33 000 символов на вход
# ([замер 27.07]: пачка крупнее — `batch size is invalid`). Ручки размера пачки в
# настройках движка нет, поэтому режем сами — генерацией запросов средствами SQL.
# Данные при этом НЕ покидают движок: текст берётся и вектор кладётся внутри базы,
# наружу уходит только вызов модели, что п. 20 разрешает явно.
#
# Параллельность — потому что вызов сетевой и ждёт: [замер] 1 поток — 6,7 строк/с,
# 2 потока — 12,7, 12 потоков — около 30. Дальше упирается в провайдера.
#
# 🔴 КАЖДЫЙ ПОТОК ПИШЕТ В СВОЮ ТАБЛИЦУ, и только потом результат переносится одним
# запросом. Это не стиль, а обход падения движка: [замер 28.07] четырнадцать
# параллельных `UPDATE ... FROM (SELECT ai_embed(...))` в ОДНУ таблицу уронили движок
# с `SIGSEGV` (systemd поднял через 3 с, данные уцелели, но досчёт встал молча).
# Запись у движка однопоточная; раздельные таблицы конфликта не создают.
#
# 🔴 ОЧЕРЁДНОСТЬ, А НЕ ОТБОР. `ROWS_WHERE` сужает ЭТОТ прогон до части строк, чтобы
# вызывающий мог посчитать сначала то, о чём спрашивают, а потом остальное. Это не фильтр
# полноты (п. 13) сам по себе: КОМУ вектор положен, решает вызывающий. С 29.07 служебным
# сущностям он не считается вовсе (решение владельца), и это НЕ молчаливая потеря —
# отсутствие вектора названо причиной в переписи (`cov_noemb_service`), а сами строки
# лежат в корпусе и в текстовом индексе, то есть находятся по словам. Сужение сделано условием, а НЕ пересортировкой: `chunk` монотонен в
# физическом порядке ключа, на этом стоят зонные карты и выборка пачки за миллисекунду
# ([замер] 0,45–1,36 мс на 97 965 строках). Сортировка по приоритету это сломала бы.
#
# Использование: embed_missing.sh <таблица> <выражение-источник> [потоков] [ключ,через,запятую]
set -u
TBL="$1"; SRC="$2"; N="${3:-8}"; KEY="${4:-}"
ROWS_WHERE="${ROWS_WHERE:-}"
[ -n "$ROWS_WHERE" ] && ROWS_WHERE="AND ($ROWS_WHERE)"
DSN="${SERENEDB_DSN:-host=127.0.0.1 port=7890 user=postgres dbname=postgres}"
MODEL="${EMBED_MODEL:-text-embedding-v4}"
# Имена секретов эмбеддера приходят от вызывающего. Их МОЖЕТ БЫТЬ НЕСКОЛЬКО — по одному
# на ключ провайдера: [замер 29.07] потолок у него на аккаунт (около двух запросов в
# секунду), и после снятия НАШЕГО ограничения скорость упёрлась в него при нуле отказов
# `429`. Потоки раскладываются по ключам по кругу, поэтому нагрузка делится поровну.
#
# Имя несёт базу, потому что секреты у движка ОБЩИЕ НА ИНСТАНС: одно имя `qwen` на все
# базы означало, что уборка одной сборки гасит эмбеддер другой ([замер 29.07]
# `ai_embed: secret 'qwen' not found` посреди чужого такта).
read -r -a SECRETS <<< "${EMBED_SECRETS:-${EMBED_SECRET:-qwen}}"
NSEC=${#SECRETS[@]}
DIM="${EMBED_DIM:-1024}"

# 🔴 МЕТКА ПОСТОЯННАЯ, ПО ИМЕНИ ТАБЛИЦЫ, а не `emb_$$`. С меткой по номеру процесса
# следующий запуск имел другой номер и НЕ находил недоделанное предыдущим: посчитанные
# векторы оставались лежать в осиротевших таблицах, а строки считались заново.
# [замер 28.07] в базе нашлось 224 719 таких строк ≈ 0,9 ГБ. С постоянной меткой
# прерванный прогон ДОКАТЫВАЕТСЯ следующим, а не выбрасывается.
#
# 🔴 И ПО ИМЕНИ БАЗЫ. Указание владельца 29.07: «разве так сложно отдельные таблицы
# сделать?» — и это правильнее фильтра. Фильтр по `database_name` надо ПОМНИТЬ в каждом
# запросе; забыл один раз — и `duckdb_tables()` показал рабочие таблицы соседней базы
# (`techContext` ловушка 25). Разные имена делают столкновение невозможным по построению,
# а фильтр остаётся вторым рубежом, а не единственным.
# Имя базы спрашиваем у движка: `dbname=` в строке подключения может быть не указан вовсе
# (`HOW_NOT_TO §3.14`).
DBNAME=$(psql "$DSN" -tAc 'SELECT current_database()' 2>/dev/null | tr -cd 'A-Za-z0-9_')
[ -n "$DBNAME" ] || { echo "движок не отвечает, имя базы не получено" >&2; exit 1; }
TAG="emb_${DBNAME}_${TBL}"

# Прежняя метка без имени базы. Нужна ровно для одного: докатить уже ПОСЧИТАННЫЕ И
# ОПЛАЧЕННЫЕ векторы, оставшиеся от прогонов до этой правки. [замер 29.07] в `ut_test`
# таких лежало 2 121 в четырёх таблицах — молча их потерять значило бы заплатить дважды.
# Когда старых таблиц не останется, ветка станет холостой и её можно будет снять.
TAG_OLD="emb_${TBL}"

# Предел длины входа. Пачка = не больше 10 строк И не больше $BUDGET символов; значение
# длиннее $MAXLEN в пачку не берётся вовсе. $BUDGET + $MAXLEN < 33 000 — это доказывает,
# что ни одна пачка не может превысить предел провайдера.
BUDGET=12000
# Предел берётся из окружения, потому что на него опираются ПРОВЕРКИ в других файлах
# (`corpus_precheck.sql`, `corpus_postcheck.sql`): строки длиннее него вектор получить не
# могут, и счёт «сделано ли то, что должно» обязан их исключать. Скопированная константа
# разошлась бы молча.
MAXLEN=${EMBED_MAXLEN:-20000}

# Ключ строки. По умолчанию — `rowid` движка, но это ЗАПАСНОЙ путь: [замер] rowid
# устойчив внутри одного прогона (удаление дыры не переиспользует, обновление не двигает),
# однако прогон теперь докатывается через рестарт движка, а устойчивость rowid через
# уплотнение никем не проверена. Вектор, легший на чужую строку, — тихая порча смысла.
# Поэтому вызывающий передаёт настоящий ключ; он есть у обеих таблиц.
if [ -n "$KEY" ]; then
  KCOLS="$KEY"
  # Условие соединения склеивается вручную. `paste -sd' AND '` здесь НЕ ГОДИТСЯ: `-d`
  # принимает СПИСОК ОДНОСИМВОЛЬНЫХ разделителей и берёт их по кругу, поэтому вместо
  # `AND` между условиями подставлялся пробел — получался синтаксически битый `UPDATE`,
  # который поток проглатывал молча, и досчёт не двигался ни на строку.
  ON=""
  for c in ${KEY//,/ }; do
    [ -n "$ON" ] && ON="$ON AND "
    ON="${ON}t.$c = p.$c"
  done
  ORD="$KEY"
else
  KCOLS="rowid AS rid"; ON="t.rowid = p.rid"; ORD="rid"
fi

T0=$(date +%s)
psql_q() { psql "$DSN" -q -v ON_ERROR_STOP=1 "$@"; }
left() { psql "$DSN" -tA -c "SELECT count(*) FROM $TBL WHERE emb IS NULL $ROWS_WHERE" 2>/dev/null; }

# 🔴 ВТОРОЙ РУБЕЖ: фильтр по базе. Первый — разные имена (метка несёт имя базы). Фильтр
# оставлен потому, что `duckdb_tables()` показывает таблицы ВСЕХ присоединённых баз, и
# полагаться на одну лишь дисциплину именования в чужом коде нельзя. [замер 29.07] из
# базы `postgres` было видно 5 рабочих таблиц базы `ut_test`; без обеих защит `transfer`
# подставил бы в `UPDATE` чужую таблицу, а `drop_parts` снёс бы чужую оплаченную работу —
# оба вреда молчаливые.
DBQ="AND database_name = current_database()"

# Перенос посчитанного из рабочих таблиц в целевую. Вызывается ДО начала работы (докатка
# прерванного прогона) и после неё. Писатель у движка один, поэтому последовательно.
# Берутся ОБЕ метки: текущая и прежняя — иначе уже оплаченные векторы старых прогонов
# остались бы лежать мёртвым грузом и были бы посчитаны заново.
transfer() {
  psql "$DSN" -tA -c "SELECT 'UPDATE $TBL t SET emb = p.emb FROM ' || table_name ||
         ' p WHERE $ON AND t.emb IS NULL;'
       FROM duckdb_tables()
       WHERE (table_name LIKE '${TAG}\_part\_%' ESCAPE '\'
           OR table_name LIKE '${TAG_OLD}\_part\_%' ESCAPE '\') $DBQ" \
    | psql "$DSN" -q >/dev/null 2>&1
}
# Уборка перечисляет РОВНО те таблицы, которые этот скрипт создаёт, а не «всё по шаблону
# `метка_%`». Со звёздочкой метка `emb_<таблица>` могла бы задеть метку другой цели, если
# база названа префиксом её имени (`emb_` + база `search` + `_corpus` = `emb_search_corpus`,
# то же, что прежняя метка таблицы `search_corpus`). Случай надуманный, но проверять это
# каждый раз глазами — та же ошибка, что полагаться на память о фильтре.
drop_parts() {
  psql "$DSN" -tA -c "SELECT 'DROP TABLE IF EXISTS ' || table_name || ';' FROM duckdb_tables()
       WHERE (table_name LIKE '${TAG}\_part\_%' ESCAPE '\' OR table_name = '${TAG}_todo'
           OR table_name LIKE '${TAG_OLD}\_part\_%' ESCAPE '\' OR table_name = '${TAG_OLD}_todo')
         $DBQ" | psql "$DSN" -q >/dev/null 2>&1
}

# Докатка: если прошлый прогон оборвался, его векторы уже посчитаны и оплачены.
transfer

n=$(left)
[ -z "$n" ] && { echo "не удалось прочитать $TBL" >&2; exit 1; }
if [ "$n" = "0" ]; then
  drop_parts
  echo "{\"таблица\":\"$TBL\",\"было_без_вектора\":0,\"осталось\":0}"
  exit 0
fi

# 🔴 РАУНДЫ, А НЕ ОДИН ЗАХОД. [замер 29.07] на одиннадцати ключах проход оборвался на
# 36 987 строках: провайдер начал отвечать `HTTP 429`, и `\gexec` с `ON_ERROR_STOP=0`
# просто пропустил отказавшие пачки. Строки при этом не терялись — они оставались с
# `emb IS NULL` и ждали СЛЕДУЮЩЕГО ТАКТА, — но такт заканчивался, сделав часть работы.
#
# Отказ по перегрузке — не ошибка данных, а «приходи позже». Поэтому: подождать и
# повторить то, что осталось. Раунд перестраивает список работы из строк, всё ещё не
# получивших вектор, поэтому уже посчитанное не пересчитывается.
#
# Выходим, когда работы не осталось ЛИБО когда раунд не сдвинул ни строки: второе значит,
# что дело не в перегрузке, и повторять бессмысленно.
impossible=0; bad=0        # на случай выхода из цикла до первого раунда
ROUNDS=${EMBED_ROUNDS:-6}
PAUSE=${EMBED_RETRY_PAUSE:-20}
round=0
while : ; do
  round=$((round + 1))
  # Отсчёт времени — ОТ НАЧАЛА РАУНДА, а не от начала прогона. Иначе счётчик строк
  # (за раунд) делится на секунды (за весь прогон), и скорость выходит заниженной:
  # [замер 29.07] второй раунд показывал 14 строк/с вместо настоящих 30.
  T0=$(date +%s)
  # 🔴 ДОКАТКА ПЕРЕД УНИЧТОЖЕНИЕМ. `transfer` переносит посчитанное в корпус, но его вывод
  # глушится, и неудавшийся перенос был неотличим от удавшегося — а следом `drop_parts`
  # сносил рабочие таблицы, и оплаченные векторы пропадали.
  # [замер 29.07] раунд 1 посчитал 13 304 строки, а остаток убыл лишь на 10 356: 2 948
  # векторов не легли и были уничтожены. Ключи при этом совпадали идеально (38 из 38),
  # то есть дело было именно в переносе, а не в несовпадении строк.
  # Повторная докатка стоит один запрос и возвращает то, что не легло с первого раза.
  transfer
  before_round=$(left)
  [ "${before_round:-0}" = "0" ] && break

drop_parts

# Пачки режутся по СИМВОЛАМ, а не только по числу строк. Прежде резалось по 10 строк, а
# предел провайдера — в символах: [замер 28.07] два значения по 560 282 символа отравляли
# свою пачку целиком, и вместе с ними вектор не получали 16 нормальных соседей — каждый
# такт, вечно, при коде возврата «успех». [замер 28.07] после этой правки все 20
# застрявших значений резолвера, включая два по 560 282 символа, получили вектор.
# `greatest` двух неубывающих величин неубывающая, поэтому колонка `chunk` остаётся
# монотонной в физическом порядке — на ней работают зонные карты, и выборка пачки стоит
# около миллисекунды вместо полного скана ([замер] 0,45–1,36 мс на 97 965 строках).
psql_q -c "CREATE OR REPLACE TABLE ${TAG}_todo AS
  WITH s AS (SELECT $KCOLS, $SRC AS txt FROM $TBL WHERE emb IS NULL $ROWS_WHERE),
       ok AS (SELECT * FROM s WHERE txt IS NOT NULL AND length(txt) BETWEEN 1 AND $MAXLEN),
       w AS (SELECT *, row_number() OVER (ORDER BY $ORD) - 1 AS rn,
                    sum(length(txt)) OVER (ORDER BY $ORD ROWS BETWEEN UNBOUNDED PRECEDING
                                                              AND 1 PRECEDING) AS cum
             FROM ok)
  SELECT * EXCLUDE (rn, cum),
         -- 🔴 СУММА, А НЕ МАКСИМУМ. «greatest» даёт монотонность, но НЕ соблюдает оба
         -- предела: если после длинного куска идут короткие строки, слагаемое по
         -- символам стоит на месте, «greatest» берёт именно его, и в пачку попадает
         -- БОЛЬШЕ десяти строк. [замер 29.07] провайдер отвергал такие пачки целиком:
         -- «HTTP 400 batch size is invalid», и раунд терял на этом часть работы.
         -- Сумма двух неубывающих величин постоянна только тогда, когда постоянны ОБА
         -- слагаемых. Значит внутри одной пачки и «rn/10» постоянен (не больше десяти
         -- строк), и «cum/BUDGET» постоянен (не больше бюджета символов) — оба предела
         -- соблюдены по построению, а не по надежде. Монотонность при этом сохраняется,
         -- поэтому зонные карты продолжают работать.
         (rn / 10) + (coalesce(cum, 0) / $BUDGET) AS chunk
  FROM w;" || exit 1

# Значения, которые вектор получить НЕ МОГУТ, — названы, а не потеряны молча (п. 13),
# и посчитаны: без этого числа «осталось без вектора» невозможно отличить недоделанную
# работу от работы, которая никогда не сдвинется.
psql "$DSN" -tA -c "SELECT 'вектор невозможен, длина ' || length($SRC) || ': ' ||
       substr(replace($SRC, chr(10), ' '), 1, 60)
     FROM $TBL WHERE emb IS NULL AND length($SRC) > $MAXLEN $ROWS_WHERE" >&2
impossible=$(psql "$DSN" -tA -c "SELECT count(*) FROM $TBL
     WHERE emb IS NULL AND (($SRC) IS NULL OR length($SRC) > $MAXLEN OR length($SRC) = 0)")
impossible=${impossible:-0}

# Журнал ошибок потоков. Прежде stderr гасился целиком, и «досчёт не сдвинулся» не
# говорило ПОЧЕМУ: [замер 29.07] на разбор «вектор не считается» ушло несколько заходов, а
# в stderr лежало готовое «OpenAI embeddings API returned HTTP 404». Ключа в этих
# операторах нет — он живёт в секрете движка, а не в тексте запроса, поэтому показывать
# первую строку ошибки безопасно (сам оператор `CREATE SECRET` создаётся в `build.sh`).
ERRDIR=$(mktemp -d); trap 'rm -rf "$ERRDIR"' EXIT

pids=()
for w in $(seq 0 $((N - 1))); do
  psql "$DSN" -q -v ON_ERROR_STOP=0 <<SQL >/dev/null 2>"$ERRDIR/$w" &
CREATE OR REPLACE TABLE ${TAG}_part_$w AS SELECT * FROM ${TAG}_todo WHERE false;
ALTER TABLE ${TAG}_part_$w DROP COLUMN txt;
ALTER TABLE ${TAG}_part_$w DROP COLUMN chunk;
ALTER TABLE ${TAG}_part_$w ADD COLUMN emb FLOAT[$DIM];
SELECT 'INSERT INTO ${TAG}_part_$w SELECT * EXCLUDE (txt, chunk), ai_embed(txt, ''$MODEL'', ''${SECRETS[$((w % NSEC))]}'')::FLOAT[$DIM]
        FROM ${TAG}_todo WHERE chunk = ' || chunk || ';'
FROM (SELECT DISTINCT chunk FROM ${TAG}_todo WHERE chunk % $N = $w ORDER BY 1)
\gexec
SQL
  pids+=($!)
done

# Коды возврата потоков собираются. Прежде `wait` без аргументов их проглатывал, и молча
# умерший поток был неотличим от отработавшего.
bad=0
for p in "${pids[@]}"; do wait "$p" || bad=$((bad + 1)); done

# `ON_ERROR_STOP=0` не даёт потоку ненулевой код: он доводит остальные операторы до конца.
# Поэтому «поток отработал» и «поток посчитал» — разные вещи, и судить надо по stderr.
# 🔴 СЧИТАЕМ ОШИБКИ, А НЕ ТОЛЬКО ПЕРВУЮ. Прежде печаталась одна строка на раунд, и по
# журналу нельзя было понять, отвалилась ли одна пачка или девять десятых. А решение
# «сколько ставить потоков и ключей» принимается именно по этому числу.
n_err=$(cat "$ERRDIR"/* 2>/dev/null | grep -cE '^(ERROR|FATAL|ОШИБКА)' || true)
n_429=$(cat "$ERRDIR"/* 2>/dev/null | grep -c 'HTTP 429' || true)
if [ "${n_err:-0}" -gt 0 ]; then
  first_err=$(cat "$ERRDIR"/* 2>/dev/null | grep -m1 -E '^(ERROR|FATAL|ОШИБКА)' || true)
  echo "досчёт: отказов пачек $n_err (из них по перегрузке $n_429). Первая: ${first_err:0:160}" >&2
fi

# 🔴 СКОЛЬКО ДАЛ КАЖДЫЙ КЛЮЧ. Считается ДО переноса и уборки, пока рабочие таблицы живы.
# Нужно, чтобы решение «добавить ещё ключей» принималось по числу, а не по ощущению:
# ключи одного аккаунта делят общую квоту и прироста не дадут, ключи разных — дадут.
# Поток `w` работает ключом `w % NSEC`, поэтому раскладка по ключам однозначна.
if [ "$NSEC" -gt 1 ]; then
  psql "$DSN" -tA -F'|' -c "SELECT 'SELECT ''' || table_name || ''', count(*) FROM ' || table_name || ';'
       FROM duckdb_tables() WHERE table_name LIKE '${TAG}\_part\_%' ESCAPE '\' $DBQ" 2>/dev/null \
    | psql "$DSN" -tA -F'|' 2>/dev/null \
    | awk -F'|' -v n="$NSEC" -v secs="$(( $(date +%s) - T0 ))" '
        { w = $1; sub(/^.*_part_/, "", w); cnt[w % n] += $2; tot += $2 }
        END { for (k = 0; k < n; k++)
                printf "  ключ %d: %d строк%s\n", k, cnt[k],
                       (secs > 0 ? sprintf(", %.1f строк/с", cnt[k] / secs) : "")
              printf "  всего: %d строк за %d с\n", tot, secs }' >&2
fi

transfer
