# Родство решает СЛОВАРЬ ДВИЖКА (`ts_lexize` по `search_dict_stem`), поэтому здесь он
# подменяется: проверяется наша часть — разбор ответа словаря и само сведение групп.
# Подстановка повторяет вид, снятый на живой сборке 26.07.3 [замер 04.08].
СТЕМЫ = {"Альтаир": "{альтаир}", "Альтаиру": "{альтаир}", "ООО Альтаир": "{оо,альтаир}",
         "Ромашка": "{ромашк}", "Сбербанк": "{сбербанк}", "BOSCH": "{bosch}",
         "техника": "{техник}", "товар": "{товар}", "товаров": "{товар}"}


def with_dict(fn):
    """Прогнать `fn` с подменённым словарём движка."""
    def fake_psql(sql):
        words = re.findall(r"ts_lexize\('[^']*', '((?:[^']|'')*)'\)", sql)
        return [[СТЕМЫ.get(w.replace("''", "'"), "{%s}" % w.lower()) for w in words]]

    real, A.psql = A.psql, fake_psql
    try:
        return fn()
    finally:
        A.psql = real


