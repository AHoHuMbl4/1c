def parse(*replies, **kw):
    """Разбор с подменённой моделью: ответы берутся по очереди, последний повторяется.

    `samples` — сколько прогонов разбора делает `parse_intent` (боевое умолчание 3);
    в проверках формы он равен 1, чтобы ответ модели и разбор соотносились один к одному.
    """
    calls, queue = [], list(replies)
    question = kw.get("question", "вопрос")

    def fake(messages, **_):
        calls.append(messages)
        return queue.pop(0) if len(queue) > 1 else (queue[0] if queue else "")

    real = (A.ds_chat, A.INTENT_SAMPLES, A.INTENT_MEMO, A.INTENT_LEAD)
    A.ds_chat, A.INTENT_SAMPLES = fake, kw.get("samples", 1)
    # Память разобранных вопросов в проверках формы выключена: иначе второй случай
    # получал бы ответ первого, и проверялась бы память, а не разбор.
    A.INTENT_MEMO, A.INTENT_LEAD = kw.get("memo", 0), kw.get("lead", 2)
    if kw.get("memo"):
        A._INTENT_MEMO.clear()
    try:
        return A.parse_intent(question, kw.get("today", "2026-08-04")), calls
    finally:
        A.ds_chat, A.INTENT_SAMPLES, A.INTENT_MEMO, A.INTENT_LEAD = real


def ok_parse(*replies, **kw):
    d, _ = parse(*replies, **kw)
    return d


